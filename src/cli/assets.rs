/// The config file used when `--config` is not given.
const DEFAULT_CONFIG: &str = "assets.toml";

/// The lockfile format this build reads and writes. Builds refuse lockfiles
/// with any other version instead of rewriting them, so bump this when adding
/// a field that an older build must not silently drop.
const LOCK_VERSION: u32 = 1;

/// The version of lockfiles that record `replaced` ids. Rojo 8.0.0 reads
/// version 1 and ignores fields it does not know, so it would drop the
/// section on its next write, losing the only record of the old ids. Only
/// lockfiles with replacements get this version, so that every other
/// lockfile stays readable by 8.0.0.
const LOCK_VERSION_REPLACED: u32 = 2;

/// Open Cloud's per-request limit for asset files.
const MAX_FILE_BYTES: u64 = 20 * 1024 * 1024;

/// Images must be smaller than this many pixels on each side.
const MAX_IMAGE_SIDE: u32 = 8000;

/// Open Cloud's limits for `displayName` and `description`.
const MAX_DISPLAY_NAME_CHARS: usize = 50;
const MAX_DESCRIPTION_CHARS: usize = 1000;

const MODULE_HEADER: &str = "--!strict\n-- Generated by rojo assets sync; do not edit.\n";

/// Uploads images, audio and models through Open Cloud and writes a Luau
/// module of their asset ids. See docs/assets.md.
#[derive(Debug, Parser)]
pub struct AssetsCommand {
    #[clap(subcommand)]
    subcommand: AssetsSubcommand,
}

#[derive(Debug, Parser)]
enum AssetsSubcommand {
    /// Upload new and changed files, then update the lockfile and the module.
    Sync {
        /// Path to the assets config.
        #[clap(long, default_value = DEFAULT_CONFIG)]
        config: PathBuf,
        /// List what would be uploaded without uploading or writing anything.
        #[clap(long)]
        dry_run: bool,
        /// Environment variable holding the Open Cloud API key. Only read when
        /// something needs uploading.
        #[clap(long, default_value = DEFAULT_API_KEY_VAR)]
        api_key_env: String,
        /// Upload files again whose exact contents Roblox rejected in
        /// moderation before. Without it such files stop the sync.
        #[clap(long)]
        retry_rejected: bool,
    },
    /// Show which files are new, changed, renamed or missing, without network
    /// access.
    Status {
        /// Path to the assets config.
        #[clap(long, default_value = DEFAULT_CONFIG)]
        config: PathBuf,
    },
    /// Find references to asset ids that sync replaced when the creator
    /// changed, and rewrite them to the new ids with --write.
    Remap {
        /// Path to the assets config.
        #[clap(long, default_value = DEFAULT_CONFIG)]
        config: PathBuf,
        /// Files or folders to scan. Defaults to the folder holding the config.
        paths: Vec<PathBuf>,
        /// Rewrite the references. Without it, only list them.
        #[clap(long)]
        write: bool,
        /// Also match bare numbers equal to an old id, such as `id = 123`.
        /// Any number can happen to equal an id, so check the list first.
        #[clap(long)]
        bare: bool,
        /// Write every old id and its new id to this JSON file, for updating
        /// place content in Studio.
        #[clap(long, value_name = "FILE")]
        map_out: Option<PathBuf>,
        /// Print a JSON report.
        #[clap(long)]
        json: bool,
    },
}

impl AssetsCommand {
    pub fn run(self) -> anyhow::Result<()> {
        let stdout = io::stdout();
        let mut out = stdout.lock();
        match self.subcommand {
            AssetsSubcommand::Sync {
                config,
                dry_run,
                api_key_env,
                retry_rejected,
            } => {
                let config = resolve_path(&config)?;
                sync(
                    &config,
                    SyncOptions {
                        dry_run,
                        retry_rejected,
                    },
                    || OpenCloud::from_env(&api_key_env),
                    &mut out,
                )?;
            }
            AssetsSubcommand::Status { config } => {
                let config = resolve_path(&config)?;
                status(&config, &mut out)?;
            }
            AssetsSubcommand::Remap {
                config,
                paths,
                write,
                bare,
                map_out,
                json,
            } => {
                let config = resolve_path(&config)?;
                let options = RemapOptions {
                    paths: paths
                        .iter()
                        .map(|path| resolve_path(path).map(|path| normalize(&path)))
                        .collect::<anyhow::Result<_>>()?,
                    write,
                    bare,
                    map_out: map_out
                        .as_deref()
                        .map(|path| resolve_path(path).map(|path| normalize(&path)))
                        .transpose()?,
                };
                let report = remap(&config, &options)?;
                if json {
                    serde_json::to_writer_pretty(&mut out, &report)?;
                    writeln!(out)?;
                } else {
                    describe_remap(&report, &mut out)?;
                }
            }
        }
        Ok(())
    }
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ConfigFile {
    /// Folder holding the assets, relative to the config.
    source: PathBuf,
    /// Luau module to write, relative to the config.
    output: PathBuf,
    creator: CreatorConfig,
    #[serde(default)]
    name_prefix: String,
    #[serde(default)]
    description: Option<String>,
    #[serde(default)]
    include: Vec<String>,
    #[serde(default)]
    exclude: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CreatorConfig {
    user_id: Option<u64>,
    group_id: Option<u64>,
}

/// A loaded config with its paths made absolute.
struct Config {
    source: PathBuf,
    output: PathBuf,
    lock: PathBuf,
    config: PathBuf,
    creator: Creator,
    name_prefix: String,
    description: Option<String>,
    include: Option<GlobSet>,
    exclude: Option<GlobSet>,
}

impl Config {
    fn creator_key(&self) -> String {
        match self.creator {
            Creator::User(id) => format!("user:{id}"),
            Creator::Group(id) => format!("group:{id}"),
        }
    }
}

fn load_config(path: &Path) -> anyhow::Result<Config> {
    let contents = match fs::read_to_string(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Err(UsageError(anyhow::anyhow!(
                "No assets config at {}. Create one as described in docs/assets.md, \
                 or pass --config.",
                path.display()
            ))
            .into())
        }
        Err(error) => return Err(error).with_context(|| format!("Cannot read {}", path.display())),
    };
    let file: ConfigFile = toml::from_str(&contents)
        .map_err(|error| UsageError(anyhow::anyhow!("{} is invalid: {error}", path.display())))?;
    let invalid = |message: String| UsageError(anyhow::anyhow!("{}: {message}", path.display()));

    let creator = match (file.creator.user_id, file.creator.group_id) {
        (Some(id), None) if id > 0 => Creator::User(id),
        (None, Some(id)) if id > 0 => Creator::Group(id),
        _ => {
            return Err(invalid(
                "[creator] needs exactly one of user_id or group_id, a positive number".to_owned(),
            )
            .into())
        }
    };
    if file.name_prefix.chars().count() >= MAX_DISPLAY_NAME_CHARS {
        return Err(invalid(format!(
            "name_prefix must be shorter than {MAX_DISPLAY_NAME_CHARS} characters, \
             since Roblox limits display names to {MAX_DISPLAY_NAME_CHARS}"
        ))
        .into());
    }
    if let Some(description) = &file.description {
        if description.chars().count() > MAX_DESCRIPTION_CHARS {
            return Err(invalid(format!(
                "description must be at most {MAX_DESCRIPTION_CHARS} characters"
            ))
            .into());
        }
    }
    let globs = |patterns: &[String]| -> anyhow::Result<Option<GlobSet>> {
        if patterns.is_empty() {
            return Ok(None);
        }
        let mut builder = GlobSetBuilder::new();
        for pattern in patterns {
            // `*` stays within one folder, like in .gitignore; `**` crosses folders.
            let glob = GlobBuilder::new(pattern)
                .literal_separator(true)
                .build()
                .map_err(|error| invalid(format!("invalid glob {pattern:?}: {error}")))?;
            builder.add(glob);
        }
        Ok(Some(builder.build()?))
    };

    let base = normalize(path.parent().unwrap_or(Path::new("")));
    let lock_name = format!(
        "{}.lock.json",
        path.file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or("assets")
    );
    Ok(Config {
        source: normalize(&base.join(&file.source)),
        output: normalize(&base.join(&file.output)),
        lock: base.join(lock_name),
        config: normalize(path),
        creator,
        name_prefix: file.name_prefix,
        description: file.description,
        include: globs(&file.include)?,
        exclude: globs(&file.exclude)?,
    })
}

/// Removes `.` and resolves `..` without touching the file system, so that
/// paths can be compared.
fn normalize(path: &Path) -> PathBuf {
    let mut normal = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                if !normal.pop() {
                    normal.push("..");
                }
            }
            other => normal.push(other),
        }
    }
    normal
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
struct LockFile {
    version: u32,
    assets: BTreeMap<String, LockEntry>,
    /// Uploads that Roblox accepted but that did not finish in an earlier
    /// run, keyed by contents (see `pending_key`) rather than by path: a
    /// path's next upload must never replace the record of an unfinished
    /// upload whose contents have since moved to another path, or those
    /// contents would be sent again. Left out when empty, so lockfiles
    /// without any stay as they were.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pending: BTreeMap<String, PendingUpload>,
    /// Contents that Roblox rejected in moderation, keyed by BLAKE3 hash.
    /// Kept so that a rejected file is not sent again on every run, since
    /// each upload creates another rejected asset on the creator's account.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    rejected: BTreeMap<String, RejectedUpload>,
    /// Asset ids that a sync replaced with a new upload because the config's
    /// creator changed, keyed by the old id. Lock entries are keyed by path
    /// and overwritten, so without this the old ids would be lost, and with
    /// them any way to find the code and place content still using them.
    /// Left out when empty, so lockfiles without any stay as they were.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    replaced: BTreeMap<String, ReplacedAsset>,
    /// Entries of another creator that an upload overwrote at their path
    /// while their contents live on at another path that has not been
    /// uploaded for the new creator yet, keyed by old asset id. Their id
    /// belongs to that other path's upload, so it is kept here until that
    /// upload records it under `replaced`; otherwise a sync interrupted in
    /// between would lose the old id for good. Emptied by every sync that
    /// finishes.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    displaced: BTreeMap<String, HeldEntry>,
}

/// An entry under `displaced`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct HeldEntry {
    #[serde(flatten)]
    entry: LockEntry,
    /// The contents of an unfinished upload that claimed this entry as the
    /// one it replaces, when that upload was dropped before finishing: Roblox
    /// failed or rejected it, or its file changed again. A later upload of
    /// those contents then records the old id, as that upload would have.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    successor_hash: Option<String>,
}

impl HeldEntry {
    fn new(entry: LockEntry) -> HeldEntry {
        HeldEntry {
            entry,
            successor_hash: None,
        }
    }
}

/// Moves the entry a dropped pending upload claimed as the one it replaces
/// into `displaced`, so that its old id is not lost and a later upload of the
/// same contents still records it. Called in the same lockfile write that
/// drops the pending upload.
fn release_claim(lock: &mut LockFile, pending: PendingUpload) {
    if let Some(replaces) = pending.replaces {
        let held = lock
            .displaced
            .entry(replaces.asset_id.to_string())
            .or_insert_with(|| HeldEntry::new(replaces));
        held.successor_hash.get_or_insert(pending.hash);
    }
}

/// An asset id replaced by an upload for another creator.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct ReplacedAsset {
    /// The latest id. When the creator changes again, earlier records are
    /// pointed at the newest id, so an old id resolves in one step.
    new_asset_id: u64,
    /// The path the replacement was uploaded from.
    path: String,
    asset_type: String,
    /// The creator the old id belongs to.
    from_creator: String,
    /// The creator `new_asset_id` belongs to.
    to_creator: String,
    /// RFC 3339 time the old id was replaced.
    replaced: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct RejectedUpload {
    /// The path the contents were uploaded from.
    path: String,
    asset_id: u64,
    asset_type: String,
    creator: String,
    /// RFC 3339 time Roblox reported the rejection.
    rejected: String,
}

/// The key of the pending upload of contents with `hash`, so that there is at
/// most one per asset type, creator and contents.
fn pending_key(asset_type: &str, creator: &str, hash: &str) -> String {
    format!("{asset_type}/{creator}/{hash}")
}

/// An upload that Roblox accepted as an operation, recorded so that the next
/// run polls the operation instead of creating a second asset.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct PendingUpload {
    /// The path the file was sent from, for messages. Empty only while
    /// reading a lockfile from before `pending` was keyed by contents, whose
    /// keys were these paths.
    #[serde(default)]
    path: String,
    /// BLAKE3 hash of the file that was sent.
    hash: String,
    asset_type: String,
    creator: String,
    /// The Assets API operation, such as `operations/abc`.
    operation: String,
    /// RFC 3339 time the file was sent.
    started: String,
    /// The entry of another creator at `path` when the file was sent, which
    /// this upload replaces. Kept here because that entry can be overwritten
    /// before the upload finishes, such as when the file is renamed and new
    /// contents are uploaded at its old path, and the old id must still map
    /// to this upload's id. While a pending upload claims an entry, no other
    /// upload records it as replaced. Left out when there is none, and in
    /// pending uploads from builds that did not record it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    replaces: Option<LockEntry>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct LockEntry {
    /// BLAKE3 hash of the file's contents, in hex.
    hash: String,
    asset_id: u64,
    /// `Image`, `Audio` or `Model`.
    asset_type: String,
    /// `user:<id>` or `group:<id>`. Ids are only reused for the same creator.
    creator: String,
    /// As Roblox reported it when the upload finished.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    moderation_state: Option<String>,
    /// RFC 3339 time of the upload.
    uploaded: String,
}

fn load_lock(path: &Path) -> anyhow::Result<LockFile> {
    let contents = match fs::read_to_string(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Ok(LockFile {
                version: LOCK_VERSION,
                ..LockFile::default()
            })
        }
        Err(error) => return Err(error).with_context(|| format!("Cannot read {}", path.display())),
    };
    let lock: LockFile = serde_json::from_str(&contents).with_context(|| {
        format!(
            "{} is not a valid assets lockfile. If a merge conflict damaged it, \
             resolve the conflict by keeping both sides' entries.",
            path.display()
        )
    })?;
    if lock.version > LOCK_VERSION_REPLACED {
        bail!(
            "{} has version {}, which a newer Rojo wrote; this Rojo only reads versions \
             {LOCK_VERSION} to {LOCK_VERSION_REPLACED}. Upgrade Rojo to sync with it.",
            path.display(),
            lock.version
        );
    }
    if lock.version < LOCK_VERSION {
        bail!(
            "{} has version {}, but this Rojo only reads versions {LOCK_VERSION} to \
             {LOCK_VERSION_REPLACED}",
            path.display(),
            lock.version
        );
    }
    Ok(rekey_pending(lock))
}

/// Keys every pending upload by its contents. Earlier builds of this format
/// keyed them by path and had no `path` field, so such a key moves into
/// `path`. Two such entries with the same contents are both waiting on an
/// asset of those contents, so keeping either one is enough.
///
/// This shape was never released, so reading it needs no version bump.
fn rekey_pending(mut lock: LockFile) -> LockFile {
    for (key, mut pending) in std::mem::take(&mut lock.pending) {
        if pending.path.is_empty() {
            pending.path = key;
        }
        lock.pending
            .entry(pending_key(
                &pending.asset_type,
                &pending.creator,
                &pending.hash,
            ))
            .or_insert(pending);
    }
    lock
}

fn render_lock(lock: &LockFile) -> String {
    // Rojo 8.0.0 would drop `replaces` from pending uploads too.
    let version = if lock.replaced.is_empty()
        && lock.displaced.is_empty()
        && lock
            .pending
            .values()
            .all(|pending| pending.replaces.is_none())
    {
        LOCK_VERSION
    } else {
        LOCK_VERSION_REPLACED
    };
    let mut text = if lock.version == version {
        serde_json::to_string_pretty(lock)
    } else {
        serde_json::to_string_pretty(&LockFile {
            version,
            ..lock.clone()
        })
    }
    .expect("lockfiles always serialize");
    text.push('\n');
    text
}

/// Writes the file through a temporary file in the same folder and a rename,
/// so a crash leaves either the old or the new contents.
fn write_atomic(path: &Path, contents: impl AsRef<[u8]>) -> anyhow::Result<()> {
    let dir = path.parent().unwrap_or(Path::new("."));
    fs::create_dir_all(dir).with_context(|| format!("Cannot create {}", dir.display()))?;
    let mut file = tempfile::NamedTempFile::new_in(dir)
        .with_context(|| format!("Cannot create a temporary file in {}", dir.display()))?;
    file.write_all(contents.as_ref())?;
    // The temporary file is only readable by its owner, so a file that is
    // rewritten in place, such as a script `rojo assets remap` updates,
    // would otherwise lose its mode.
    #[cfg(unix)]
    if let Ok(metadata) = fs::metadata(path) {
        let _ = file.as_file().set_permissions(metadata.permissions());
    }
    file.as_file().sync_all()?;
    file.persist(path)
        .map_err(|error| error.error)
        .with_context(|| format!("Cannot write {}", path.display()))?;
    // On Unix the rename itself is only durable once the folder is synced.
    // Failing to sync is not worth failing the write over.
    #[cfg(unix)]
    if let Ok(dir) = fs::File::open(dir) {
        let _ = dir.sync_all();
    }
    Ok(())
}

/// Writes the file only when its contents differ. Returns whether it wrote.
fn write_if_changed(path: &Path, contents: &str) -> anyhow::Result<bool> {
    if fs::read_to_string(path).ok().as_deref() == Some(contents) {
        return Ok(false);
    }
    write_atomic(path, contents)?;
    Ok(true)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Image,
    Audio,
    Model,
}

impl Kind {
    fn name(self) -> &'static str {
        match self {
            Kind::Image => "Image",
            Kind::Audio => "Audio",
            Kind::Model => "Model",
        }
    }

    fn asset_type(self) -> AssetType {
        match self {
            // Image ids work directly in `rbxassetid://`; Decal ids do not.
            Kind::Image => AssetType::Image,
            Kind::Audio => AssetType::Audio,
            Kind::Model => AssetType::Model,
        }
    }
}

/// Picks the asset type and content type from a lowercase extension, or says
/// why the file cannot be uploaded.
fn classify(extension: &str) -> Result<(Kind, &'static str), &'static str> {
    Ok(match extension {
        "png" => (Kind::Image, "image/png"),
        "jpg" | "jpeg" => (Kind::Image, "image/jpeg"),
        "bmp" => (Kind::Image, "image/bmp"),
        "tga" => (Kind::Image, "image/tga"),
        "mp3" => (Kind::Audio, "audio/mpeg"),
        "ogg" => (Kind::Audio, "audio/ogg"),
        "flac" => (Kind::Audio, "audio/flac"),
        "wav" => (Kind::Audio, "audio/wav"),
        "fbx" => (Kind::Model, "model/fbx"),
        "gltf" => (Kind::Model, "model/gltf+json"),
        "glb" => (Kind::Model, "model/gltf-binary"),
        "obj" => {
            return Err("Open Cloud does not accept OBJ models; export it as FBX, glTF or GLB")
        }
        _ => {
            return Err(
                "not a format Open Cloud accepts (png, jpg, jpeg, bmp, tga, mp3, ogg, flac, \
                 wav, fbx, gltf, glb); add it to `exclude` to silence this",
            )
        }
    })
}

/// One file to sync.
#[derive(Debug, Clone)]
struct Source {
    /// Path relative to the source folder, with `/` separators.
    rel: String,
    path: PathBuf,
    kind: Kind,
    content_type: &'static str,
    hash: String,
    size: u64,
}

struct Scan {
    sources: Vec<Source>,
    warnings: Vec<String>,
}

/// Finds, hashes and checks every file. Fails with every problem found when
/// any file cannot be uploaded or two files would get the same module key.
fn scan(config: &Config) -> anyhow::Result<Scan> {
    if !config.source.is_dir() {
        return Err(UsageError(anyhow::anyhow!(
            "The asset folder {} does not exist",
            config.source.display()
        ))
        .into());
    }
    let mut files = Vec::new();
    walk(&config.source, "", &mut files)?;

    let ignored = [&config.output, &config.lock, &config.config];
    let mut sources = Vec::new();
    let mut warnings = Vec::new();
    let mut errors = Vec::new();
    for (rel, path) in files {
        let rel_path = Path::new(&rel);
        if ignored.iter().any(|ignored| **ignored == path)
            || config
                .include
                .as_ref()
                .is_some_and(|include| !include.is_match(rel_path))
            || config
                .exclude
                .as_ref()
                .is_some_and(|exclude| exclude.is_match(rel_path))
        {
            continue;
        }
        let extension = rel_path
            .extension()
            .and_then(|extension| extension.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        let (kind, content_type) = match classify(&extension) {
            Ok(classified) => classified,
            Err(reason) => {
                warnings.push(format!("skipped {rel}: {reason}"));
                continue;
            }
        };
        // Checking the size first keeps a stray multi-gigabyte file from
        // being read into memory only to be refused.
        let size = fs::metadata(&path)
            .with_context(|| format!("Cannot read {}", path.display()))?
            .len();
        if let Err(problem) = check_size(size) {
            errors.push(format!("{rel}: {problem}"));
            continue;
        }
        let bytes = fs::read(&path).with_context(|| format!("Cannot read {}", path.display()))?;
        if let Err(problem) = check_file(&extension, &bytes) {
            errors.push(format!("{rel}: {problem}"));
            continue;
        }
        sources.push(Source {
            hash: blake3::hash(&bytes).to_hex().to_string(),
            size: bytes.len() as u64,
            rel,
            path,
            kind,
            content_type,
        });
    }

    if let Err(collisions) = build_tree(sources.iter().map(|source| (source.rel.as_str(), 0))) {
        errors.extend(collisions);
    }
    if !errors.is_empty() {
        bail!(
            "Cannot sync assets; nothing was uploaded:\n  {}",
            errors.join("\n  ")
        );
    }
    Ok(Scan { sources, warnings })
}

/// Lists files under `dir` in a stable order. Hidden files and folders, such
/// as `.DS_Store`, are skipped, and symbolic links to folders are not
/// followed so that a link cannot loop.
fn walk(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) -> anyhow::Result<()> {
    let mut entries = fs::read_dir(dir)
        .with_context(|| format!("Cannot list {}", dir.display()))?
        .collect::<Result<Vec<_>, _>>()
        .with_context(|| format!("Cannot list {}", dir.display()))?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            bail!(
                "{} has a name that is not valid Unicode",
                entry.path().display()
            );
        };
        if name.starts_with('.') {
            continue;
        }
        let rel = format!("{prefix}{name}");
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            walk(&path, &format!("{rel}/"), files)?;
        } else if file_type.is_file() || (file_type.is_symlink() && path.is_file()) {
            files.push((rel, path));
        }
    }
    Ok(())
}

/// Checks a file against Open Cloud's limits and its format's signature, so
/// that problems show up before anything is uploaded.
fn check_file(extension: &str, bytes: &[u8]) -> Result<(), String> {
    // Checked again since the file may have changed after its metadata was
    // read.
    check_size(bytes.len() as u64)?;
    let not_valid = |format: &str| Err(format!("the file is not a valid {format} file"));
    match extension {
        "png" | "jpg" | "jpeg" | "bmp" | "tga" => {
            let Some((width, height)) = image_size(extension, bytes) else {
                return not_valid(&extension.to_ascii_uppercase());
            };
            if width >= MAX_IMAGE_SIDE || height >= MAX_IMAGE_SIDE {
                return Err(format!(
                    "the image is {width}x{height}; Roblox accepts images smaller than \
                     {MAX_IMAGE_SIDE}x{MAX_IMAGE_SIDE}"
                ));
            }
        }
        "mp3" => {
            let frame = bytes.len() >= 2 && bytes[0] == 0xFF && bytes[1] & 0xE0 == 0xE0;
            if !(bytes.starts_with(b"ID3") || frame) {
                return not_valid("MP3");
            }
        }
        "ogg" if !bytes.starts_with(b"OggS") => return not_valid("Ogg"),
        "flac" if !bytes.starts_with(b"fLaC") => return not_valid("FLAC"),
        "wav" if !(bytes.starts_with(b"RIFF") && bytes.get(8..12) == Some(b"WAVE")) => {
            return not_valid("WAV")
        }
        "glb" if !bytes.starts_with(b"glTF") => return not_valid("GLB"),
        "gltf" => check_gltf(bytes)?,
        _ => {}
    }
    Ok(())
}

fn check_size(size: u64) -> Result<(), String> {
    if size == 0 {
        return Err("the file is empty".to_owned());
    }
    if size > MAX_FILE_BYTES {
        // Exact byte counts, since a rounded size just over the limit reads
        // as if it were within it.
        return Err(format!(
            "the file is {size} bytes; Open Cloud accepts files up to {MAX_FILE_BYTES} bytes \
             (20 MB)"
        ));
    }
    Ok(())
}

/// Open Cloud receives a single file, so a glTF that points at separate
/// buffer or texture files would arrive incomplete.
fn check_gltf(bytes: &[u8]) -> Result<(), String> {
    let gltf: serde_json::Value =
        serde_json::from_slice(bytes).map_err(|_| "the file is not valid glTF JSON".to_owned())?;
    for list in ["buffers", "images"] {
        for item in gltf[list].as_array().into_iter().flatten() {
            if let Some(uri) = item["uri"].as_str() {
                if !uri.starts_with("data:") {
                    return Err(format!(
                        "it refers to the separate file {uri:?}, which Open Cloud cannot \
                         receive; export it as GLB or with embedded resources"
                    ));
                }
            }
        }
    }
    Ok(())
}

/// Reads an image's width and height from its header.
fn image_size(extension: &str, bytes: &[u8]) -> Option<(u32, u32)> {
    let be32 = |at: usize| Some(u32::from_be_bytes(bytes.get(at..at + 4)?.try_into().ok()?));
    let le32 = |at: usize| Some(i32::from_le_bytes(bytes.get(at..at + 4)?.try_into().ok()?));
    let le16 = |at: usize| Some(u16::from_le_bytes(bytes.get(at..at + 2)?.try_into().ok()?));
    let be16 = |at: usize| Some(u16::from_be_bytes(bytes.get(at..at + 2)?.try_into().ok()?));
    match extension {
        "png" => {
            if !bytes.starts_with(b"\x89PNG\r\n\x1a\n") || bytes.get(12..16) != Some(b"IHDR") {
                return None;
            }
            Some((be32(16)?, be32(20)?))
        }
        "bmp" => {
            if !bytes.starts_with(b"BM") {
                return None;
            }
            // Height is negative for top-down bitmaps.
            Some((le32(18)?.unsigned_abs(), le32(22)?.unsigned_abs()))
        }
        // TGA has no signature; its size is at a fixed offset.
        "tga" => Some((u32::from(le16(12)?), u32::from(le16(14)?))),
        _ => {
            // JPEG: walk the segments until a start-of-frame marker.
            if !bytes.starts_with(&[0xFF, 0xD8]) {
                return None;
            }
            let mut at = 2;
            loop {
                if *bytes.get(at)? != 0xFF {
                    return None;
                }
                let marker = *bytes.get(at + 1)?;
                match marker {
                    // Fill bytes, and markers without a length.
                    0xFF => at += 1,
                    0x01 | 0xD0..=0xD7 => at += 2,
                    0xC0..=0xCF if !matches!(marker, 0xC4 | 0xC8 | 0xCC) => {
                        return Some((u32::from(be16(at + 7)?), u32::from(be16(at + 5)?)));
                    }
                    0xD9 | 0xDA => return None,
                    _ => at += 2 + usize::from(be16(at + 2)?),
                }
            }
        }
    }
}

/// A module table: folders become nested tables, files become ids.
enum Node<'a> {
    Folder {
        path: String,
        children: BTreeMap<String, Node<'a>>,
    },
    Asset {
        rel: &'a str,
        id: u64,
    },
}

/// Builds the module's tables, keyed by folder names and file names without
/// their extension. Fails with one message per pair of paths that would get
/// the same key.
fn build_tree<'a>(
    assets: impl IntoIterator<Item = (&'a str, u64)>,
) -> Result<BTreeMap<String, Node<'a>>, Vec<String>> {
    let mut root = BTreeMap::new();
    let mut errors = Vec::new();
    'assets: for (rel, id) in assets {
        let mut parts: Vec<&str> = rel.split('/').collect();
        let file = parts.pop().unwrap_or(rel);
        let key = match file.rsplit_once('.') {
            Some((stem, _)) if !stem.is_empty() => stem,
            _ => file,
        };
        let mut table = &mut root;
        let mut folder = String::new();
        for part in parts {
            folder.push_str(part);
            let node = table
                .entry(part.to_owned())
                .or_insert_with(|| Node::Folder {
                    path: folder.clone(),
                    children: BTreeMap::new(),
                });
            folder.push('/');
            match node {
                Node::Folder { children, .. } => table = children,
                Node::Asset { rel: other, .. } => {
                    errors.push(format!(
                        "{other} and the folder {} would both be named {part:?} in the module; \
                         rename one of them",
                        folder.trim_end_matches('/')
                    ));
                    continue 'assets;
                }
            }
        }
        match table.get(key) {
            None => {
                table.insert(key.to_owned(), Node::Asset { rel, id });
            }
            Some(Node::Asset { rel: other, .. }) => errors.push(format!(
                "{other} and {rel} would both be named {key:?} in the module; rename one of them"
            )),
            Some(Node::Folder { path, .. }) => errors.push(format!(
                "{rel} and the folder {path} would both be named {key:?} in the module; \
                 rename one of them"
            )),
        }
    }
    if errors.is_empty() {
        Ok(root)
    } else {
        Err(errors)
    }
}

fn render_module(tree: &BTreeMap<String, Node<'_>>) -> String {
    fn table(output: &mut String, children: &BTreeMap<String, Node<'_>>, depth: usize) {
        if children.is_empty() {
            output.push_str("{}");
            return;
        }
        output.push_str("{\n");
        for (key, node) in children {
            output.push_str(&"\t".repeat(depth + 1));
            write_key(output, key);
            output.push_str(" = ");
            match node {
                Node::Folder { children, .. } => table(output, children, depth + 1),
                Node::Asset { id, .. } => write!(output, "\"rbxassetid://{id}\"").unwrap(),
            }
            output.push_str(",\n");
        }
        output.push_str(&"\t".repeat(depth));
        output.push('}');
    }
    let mut output = format!("{MODULE_HEADER}\nreturn ");
    table(&mut output, tree, 0);
    output.push('\n');
    output
}

fn write_key(output: &mut String, key: &str) {
    if is_valid_ident(key) {
        output.push_str(key);
        return;
    }
    output.push_str("[\"");
    for c in key.chars() {
        match c {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            // Three digits, so a digit that follows is not read as part of
            // the escape.
            c if c.is_ascii_control() => write!(output, "\\{:03}", c as u32).unwrap(),
            c => output.push(c),
        }
    }
    output.push_str("\"]");
}

fn is_valid_ident(value: &str) -> bool {
    // Luau's contextual keywords (`continue`, `type`, `export`) are valid
    // field names, so only the reserved words are listed.
    const KEYWORDS: &[&str] = &[
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
        "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
    ];
    let mut chars = value.chars();
    matches!(chars.next(), Some(first) if first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !KEYWORDS.contains(&value)
}

#[derive(Debug, Clone, PartialEq)]
enum Action {
    Unchanged,
    /// Upload because the path is new, or because its contents changed.
    Upload {
        changed: bool,
        /// An earlier run's unfinished upload of the same contents, which is
        /// polled instead of sending the file again.
        resume: Option<Resume>,
    },
    /// Reuse an id from the lockfile for the same contents at another path.
    Reuse {
        from: String,
        entry: LockEntry,
    },
    /// Reuse the id of an identical file uploaded earlier in this run.
    SameAs {
        from: String,
    },
    /// Not uploaded, because Roblox rejected these exact contents in
    /// moderation before and `--retry-rejected` was not given.
    Rejected(RejectedUpload),
}

#[derive(Debug, Clone, PartialEq)]
struct Resume {
    /// The key of the entry in the lockfile's `pending`.
    key: String,
    operation: String,
}

struct Plan {
    items: Vec<(Source, Action)>,
    /// Lockfile paths whose files are gone.
    removed: Vec<String>,
    /// Pending uploads that no file resumes, because the file changed, is
    /// gone or got an id another way. Dropped after a successful sync.
    stale_pending: Vec<String>,
}

impl Plan {
    fn uploads(&self) -> usize {
        self.items
            .iter()
            .filter(|(_, action)| matches!(action, Action::Upload { .. }))
            .count()
    }

    fn rejected(&self) -> Vec<(&Source, &RejectedUpload)> {
        self.items
            .iter()
            .filter_map(|(source, action)| match action {
                Action::Rejected(rejected) => Some((source, rejected)),
                _ => None,
            })
            .collect()
    }
}

fn plan(sources: &[Source], lock: &LockFile, config: &Config, retry_rejected: bool) -> Plan {
    let creator = config.creator_key();
    let reusable = |entry: &LockEntry, source: &Source| {
        entry.creator == creator && entry.asset_type == source.kind.name()
    };

    // The first path in sorted order wins when several share contents.
    let mut by_hash: HashMap<&str, (&str, &LockEntry)> = HashMap::new();
    for (rel, entry) in &lock.assets {
        if entry.creator == creator {
            by_hash.entry(&entry.hash).or_insert((rel, entry));
        }
    }
    // An id held for contents that moved while a creator change was
    // interrupted belongs to this creator again if the config switched back,
    // so those contents get it back instead of a new upload. It has no path,
    // which `from` marks with an empty string.
    for entry in lock.displaced.values().map(|held| &held.entry) {
        if entry.creator == creator {
            by_hash.entry(&entry.hash).or_insert(("", entry));
        }
    }
    let mut uploading: HashMap<&str, &str> = HashMap::new();
    let mut items = Vec::new();
    for source in sources {
        let existing = lock.assets.get(&source.rel);
        let action = match existing {
            Some(entry) if entry.hash == source.hash && reusable(entry, source) => {
                Action::Unchanged
            }
            _ => match by_hash.get(source.hash.as_str()) {
                Some((from, entry)) if reusable(entry, source) => Action::Reuse {
                    from: (*from).to_owned(),
                    entry: (*entry).clone(),
                },
                _ => match uploading.get(source.hash.as_str()) {
                    Some(from) => Action::SameAs {
                        from: (*from).to_owned(),
                    },
                    None => {
                        // Found by contents, so it follows a rename.
                        let resume = lock
                            .pending
                            .get_key_value(&pending_key(source.kind.name(), &creator, &source.hash))
                            .map(|(key, pending)| Resume {
                                key: key.clone(),
                                operation: pending.operation.clone(),
                            });
                        // Checking on a pending upload sends nothing, so it
                        // goes ahead even for rejected contents.
                        let rejected = lock.rejected.get(&source.hash).filter(|rejected| {
                            !retry_rejected
                                && resume.is_none()
                                && rejected.creator == creator
                                && rejected.asset_type == source.kind.name()
                        });
                        match rejected {
                            Some(rejected) => Action::Rejected(rejected.clone()),
                            None => {
                                uploading.insert(&source.hash, &source.rel);
                                Action::Upload {
                                    changed: existing.is_some(),
                                    resume,
                                }
                            }
                        }
                    }
                },
            },
        };
        items.push((source.clone(), action));
    }
    let present: BTreeSet<&str> = sources.iter().map(|source| source.rel.as_str()).collect();
    let removed = lock
        .assets
        .keys()
        .filter(|rel| !present.contains(rel.as_str()))
        .cloned()
        .collect();
    let resumed: BTreeSet<&str> = items
        .iter()
        .filter_map(|(_, action)| match action {
            Action::Upload {
                resume: Some(resume),
                ..
            } => Some(resume.key.as_str()),
            _ => None,
        })
        .collect();
    // Pending uploads for another creator are kept: switching the config's
    // creator back resumes them instead of uploading those contents again.
    let stale_pending = lock
        .pending
        .iter()
        .filter(|(key, pending)| pending.creator == creator && !resumed.contains(key.as_str()))
        .map(|(key, _)| key.clone())
        .collect();
    Plan {
        items,
        removed,
        stale_pending,
    }
}

fn describe_plan(
    plan: &Plan,
    lock: &LockFile,
    dry_run: bool,
    out: &mut dyn Write,
) -> io::Result<()> {
    let upload_verb = if dry_run { "would upload" } else { "to upload" };
    for (source, action) in &plan.items {
        match action {
            Action::Unchanged => {}
            Action::Upload {
                resume: Some(resume),
                ..
            } => writeln!(
                out,
                "  resume    {} ({}, {}) {} {}, which an earlier sync started",
                source.rel,
                source.kind.name(),
                format_size(source.size),
                if dry_run {
                    "would check on"
                } else {
                    "to check on"
                },
                resume.operation
            )?,
            Action::Upload { changed, .. } => writeln!(
                out,
                "  {:<9} {} ({}, {}) {upload_verb}",
                if *changed { "changed" } else { "new" },
                source.rel,
                source.kind.name(),
                format_size(source.size)
            )?,
            Action::Reuse { from, entry } if from.is_empty() => writeln!(
                out,
                "  restore   {} (gets back asset {}, held by an interrupted sync)",
                source.rel, entry.asset_id
            )?,
            Action::Reuse { from, entry } if plan.removed.contains(from) => writeln!(
                out,
                "  renamed   {from} -> {} (keeps asset {})",
                source.rel, entry.asset_id
            )?,
            Action::Reuse { from, entry } => writeln!(
                out,
                "  copy      {} (same contents as {from}, reuses asset {})",
                source.rel, entry.asset_id
            )?,
            Action::SameAs { from } => writeln!(
                out,
                "  copy      {} (same contents as {from}, reuses its upload)",
                source.rel
            )?,
            Action::Rejected(rejected) => writeln!(
                out,
                "  rejected  {} ({}) was rejected in moderation as asset {} on {} and is not \
                 uploaded again; replace the file or pass --retry-rejected",
                source.rel,
                source.kind.name(),
                rejected.asset_id,
                rejected.rejected
            )?,
        }
    }
    let renamed: BTreeSet<&str> = plan
        .items
        .iter()
        .filter_map(|(_, action)| match action {
            Action::Reuse { from, .. } => Some(from.as_str()),
            _ => None,
        })
        .collect();
    for rel in &plan.removed {
        if !renamed.contains(rel.as_str()) {
            writeln!(
                out,
                "  missing   {rel} (asset {} stays on Roblox)",
                lock.assets[rel].asset_id
            )?;
        }
    }
    for key in &plan.stale_pending {
        let pending = &lock.pending[key];
        writeln!(
            out,
            "  stale     unfinished upload of {} ({}) is no longer needed and will be \
             forgotten; if Roblox created an asset for it, that asset stays unused",
            pending.path, pending.operation
        )?;
    }
    Ok(())
}

fn format_size(bytes: u64) -> String {
    if bytes < 1024 {
        format!("{bytes} B")
    } else if bytes < 1024 * 1024 {
        format!("{:.1} KB", bytes as f64 / 1024.0)
    } else {
        format!("{:.1} MB", bytes as f64 / (1024.0 * 1024.0))
    }
}

/// The lockfile after applying every change that needs no upload: reused ids
/// and removals.
fn offline_lock(plan: &Plan, lock: &LockFile) -> LockFile {
    let mut next = lock.clone();
    for (source, action) in &plan.items {
        if let Action::Reuse { entry, .. } = action {
            next.assets.insert(source.rel.clone(), entry.clone());
        }
    }
    for rel in &plan.removed {
        next.assets.remove(rel);
    }
    next
}

fn module_for(sources: &[Source], lock: &LockFile) -> Option<String> {
    let ids: Option<Vec<(&str, u64)>> = sources
        .iter()
        .map(|source| {
            let entry = lock.assets.get(&source.rel)?;
            Some((source.rel.as_str(), entry.asset_id))
        })
        .collect();
    let tree = build_tree(ids?).expect("collisions were checked while scanning");
    Some(render_module(&tree))
}

fn display_path(config: &Config, path: &Path) -> String {
    let base = config.config.parent().unwrap_or(Path::new(""));
    path.strip_prefix(base)
        .unwrap_or(path)
        .display()
        .to_string()
        .replace('\\', "/")
}

/// Reports what `sync` would do, without network access.
fn status(config_path: &Path, out: &mut dyn Write) -> anyhow::Result<()> {
    let config = load_config(config_path)?;
    let scan = scan(&config)?;
    for warning in &scan.warnings {
        writeln!(out, "warning: {warning}")?;
    }
    let lock = load_lock(&config.lock)?;
    let plan = plan(&scan.sources, &lock, &config, false);
    describe_plan(&plan, &lock, false, out)?;
    for (rel, entry) in &lock.assets {
        if let Some(state) = entry
            .moderation_state
            .as_deref()
            .filter(|state| *state != "Approved")
        {
            writeln!(
                out,
                "  moderation {rel} (asset {} was {state} when uploaded)",
                entry.asset_id
            )?;
        }
    }

    let unchanged = plan
        .items
        .iter()
        .filter(|(_, action)| *action == Action::Unchanged)
        .count();
    let uploads = plan.uploads();
    let rejected = plan.rejected().len();
    writeln!(
        out,
        "{} file(s): {unchanged} unchanged, {uploads} to upload, {} reusing an id, {rejected} \
         rejected, {} removed.",
        plan.items.len(),
        plan.items.len() - unchanged - uploads - rejected,
        plan.removed.len()
    )?;
    let output = display_path(&config, &config.output);
    let module = module_for(&scan.sources, &offline_lock(&plan, &lock));
    let current = fs::read_to_string(&config.output).ok();
    match module {
        _ if rejected > 0 => writeln!(
            out,
            "Replace the rejected file(s), or pass --retry-rejected to `rojo assets sync`, to \
             update {output}."
        )?,
        _ if uploads > 0 => writeln!(out, "Run `rojo assets sync` to upload and update {output}.")?,
        Some(module) if current.as_deref() == Some(module.as_str()) => {
            writeln!(out, "{output} is up to date.")?
        }
        _ => writeln!(out, "Run `rojo assets sync` to update {output}.")?,
    }
    if !lock.replaced.is_empty() {
        writeln!(
            out,
            "{} asset id(s) were replaced when the creator changed. Run `rojo assets remap` to \
             list code still using the old ids, then `rojo assets remap --write` to update it.",
            lock.replaced.len()
        )?;
    }
    Ok(())
}

/// What a sync did.
#[derive(Debug, Default, PartialEq)]
struct SyncReport {
    uploaded: Vec<(String, u64)>,
    module_written: bool,
}

#[derive(Debug, Clone, Copy, Default)]
struct SyncOptions {
    dry_run: bool,
    retry_rejected: bool,
}

/// Held for the whole of a sync that may write, so that two syncs of one
/// config cannot both read the lockfile and upload the same new files. The
/// file is removed when the guard drops, including on errors and panics; a
/// killed process leaves it behind, and so does Ctrl+C, since Rojo installs
/// no handler and the process ends without unwinding. The error for a
/// leftover file explains how to remove it.
struct SyncLock {
    path: PathBuf,
}

impl SyncLock {
    fn acquire(config: &Config) -> anyhow::Result<SyncLock> {
        let mut name = config.lock.file_name().unwrap_or_default().to_owned();
        name.push(".lock");
        let path = config.lock.with_file_name(name);
        match fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
        {
            Ok(mut file) => {
                let guard = SyncLock { path };
                // The contents only help someone deciding whether the lock is
                // stale, so failing to write them is not an error.
                let _ = write!(
                    file,
                    "pid {}\nstarted {}\n",
                    std::process::id(),
                    humantime::format_rfc3339_seconds(SystemTime::now())
                );
                Ok(guard)
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {
                let holder = fs::read_to_string(&path).unwrap_or_default();
                let holder = holder.split_whitespace().collect::<Vec<_>>().join(" ");
                let display = display_path(config, &path);
                bail!(
                    "Another `rojo assets sync` is running for this config: {display} exists{}. \
                     Wait for it to finish. If no sync is running, for example because one was \
                     killed, delete {display} and run sync again.",
                    if holder.is_empty() {
                        String::new()
                    } else {
                        format!(" ({holder})")
                    }
                )
            }
            Err(error) => Err(error).with_context(|| format!("Cannot create {}", path.display())),
        }
    }
}

impl Drop for SyncLock {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.path);
    }
}

fn sync(
    config_path: &Path,
    options: SyncOptions,
    connect: impl FnOnce() -> anyhow::Result<OpenCloud>,
    out: &mut dyn Write,
) -> anyhow::Result<SyncReport> {
    let SyncOptions {
        dry_run,
        retry_rejected,
    } = options;
    let config = load_config(config_path)?;
    // Taken before the lockfile is read, since a second sync that read it
    // while this one uploads would upload the same files. A dry run writes
    // nothing, so it does not need the lock.
    let _sync_lock = if dry_run {
        None
    } else {
        Some(SyncLock::acquire(&config)?)
    };
    let scan = scan(&config)?;
    for warning in &scan.warnings {
        writeln!(out, "warning: {warning}")?;
    }
    let old_lock = load_lock(&config.lock)?;
    let plan = plan(&scan.sources, &old_lock, &config, retry_rejected);
    describe_plan(&plan, &old_lock, dry_run, out)?;
    let total = plan.uploads();
    let output = display_path(&config, &config.output);
    let rejected = plan.rejected();
    if dry_run {
        writeln!(
            out,
            "Dry run: {total} file(s) would be uploaded. Nothing was uploaded or written."
        )?;
        if !rejected.is_empty() {
            writeln!(
                out,
                "A sync would stop before uploading: {} file(s) were rejected in moderation \
                 before.",
                rejected.len()
            )?;
        }
        return Ok(SyncReport::default());
    }
    // Like a file that fails the size checks, this stops the run before
    // anything is uploaded, since the module needs an id for every file.
    if !rejected.is_empty() {
        let list: Vec<String> = rejected
            .iter()
            .map(|(source, rejected)| {
                format!(
                    "{} (asset {}, rejected on {})",
                    source.rel, rejected.asset_id, rejected.rejected
                )
            })
            .collect();
        bail!(
            "Roblox rejected the contents of {} in moderation in an earlier sync, so they are not \
             uploaded again: each upload would create another rejected asset. Replace or \
             exclude the file(s), or pass --retry-rejected to upload them again.",
            list.join(", ")
        );
    }

    let mut report = SyncReport::default();
    let mut lock = old_lock.clone();
    let current_hashes: HashSet<&str> = scan
        .sources
        .iter()
        .map(|source| source.hash.as_str())
        .collect();
    let set_entry =
        |lock: &mut LockFile, source: &Source, entry: LockEntry, from: Option<&LockEntry>| {
            replace_entry(lock, &old_lock, &current_hashes, source, entry, from)
        };
    // Recording reused ids first keeps them when an upload below replaces the
    // entry they were copied from and the run is then interrupted.
    for (source, action) in &plan.items {
        if let Action::Reuse { entry, .. } = action {
            // A sync for a new creator that was interrupted reuses the new
            // creator's id on its next run, so this is a replacement too.
            set_entry(&mut lock, source, entry.clone(), None);
        }
    }
    if lock != old_lock {
        write_atomic(&config.lock, render_lock(&lock))?;
    }

    if total > 0 {
        let client = connect()?;
        let creator = config.creator_key();
        let uploads = plan
            .items
            .iter()
            .filter_map(|(source, action)| match action {
                Action::Upload { resume, .. } => Some((source, resume)),
                _ => None,
            });
        for (index, (source, resume)) in uploads.enumerate() {
            match resume {
                Some(resume) => write!(
                    out,
                    "[{}/{total}] Checking on the earlier upload of {} ({})... ",
                    index + 1,
                    source.rel,
                    resume.operation
                )?,
                None => write!(
                    out,
                    "[{}/{total}] Uploading {} ({}, {})... ",
                    index + 1,
                    source.rel,
                    source.kind.name(),
                    format_size(source.size)
                )?,
            }
            out.flush()?;
            let entry = upload(
                &client,
                &config,
                source,
                resume.as_ref(),
                &creator,
                &current_hashes,
                &mut lock,
            )
            .map_err(|error| {
                let saved = report.uploaded.len();
                error.context(format!(
                    "{saved} earlier upload(s) in this run were saved to {}",
                    display_path(&config, &config.lock)
                ))
            })?;
            match entry.moderation_state.as_deref() {
                Some("Approved") | None => writeln!(out, "asset {}", entry.asset_id)?,
                Some(state) => {
                    writeln!(out, "asset {} ({state})", entry.asset_id)?;
                    writeln!(
                        out,
                        "warning: {} is {state} in moderation; its id is recorded but may not \
                         load until Roblox approves it",
                        source.rel
                    )?;
                }
            }
            report.uploaded.push((source.rel.clone(), entry.asset_id));
            // Contents retried with --retry-rejected that passed this time.
            lock.rejected.remove(&source.hash);
            // A resumed upload replaces what its pending record says it was
            // replacing when it was sent: the file may have been renamed and
            // its old path overwritten since. Pending uploads from builds
            // that did not record it fall back to the entry at the path they
            // were sent from.
            let predecessor = resume
                .as_ref()
                .and_then(|resume| old_lock.pending.get(&resume.key))
                .and_then(|pending| {
                    pending.replaces.clone().or_else(|| {
                        old_lock
                            .assets
                            .get(&pending.path)
                            .filter(|previous| {
                                !pending.path.is_empty()
                                    && may_claim(previous, source, &current_hashes)
                                    && !is_claimed(&lock, previous.asset_id)
                            })
                            .cloned()
                    })
                });
            // Recorded in the same write as the entry that overwrites the
            // old id, so an interrupted run never loses the old id.
            set_entry(&mut lock, source, entry, predecessor.as_ref());
            write_atomic(&config.lock, render_lock(&lock))?;
        }
    }

    for (source, action) in &plan.items {
        if let Action::SameAs { from } = action {
            let entry = lock.assets[from].clone();
            set_entry(&mut lock, source, entry, None);
        }
    }
    // Every file now has an entry for this creator, so a displaced id whose
    // contents a file still has is recorded here at the latest, and one whose
    // contents are gone has no new id to map to.
    if !lock.displaced.is_empty() {
        for source in &scan.sources {
            if lock.displaced.values().any(|held| {
                held.entry.hash == source.hash
                    || held.successor_hash.as_deref() == Some(source.hash.as_str())
            }) {
                let entry = lock.assets[&source.rel].clone();
                record_replacements(&mut lock, &old_lock, &current_hashes, source, &entry, None);
            }
        }
        lock.displaced.clear();
    }
    for rel in &plan.removed {
        lock.assets.remove(rel);
    }
    // After the clearing above, so that a claim released here is kept for a
    // later sync, which may upload the claimed contents again; the next sync
    // that finishes drops it if none does.
    for key in &plan.stale_pending {
        if let Some(pending) = lock.pending.remove(key) {
            release_claim(&mut lock, pending);
        }
    }
    // An id in use by this creator is current, whatever an earlier creator
    // change recorded for it: switching back after an interrupted move can
    // leave a file `Unchanged` with an id that is also recorded as replaced,
    // and `remap` would then rewrite valid references to the other
    // creator's id. Reconciled against every entry, since unchanged ones
    // never pass through `replace_entry`.
    let creator = config.creator_key();
    let current_ids: BTreeSet<String> = lock
        .assets
        .values()
        .filter(|entry| entry.creator == creator)
        .map(|entry| entry.asset_id.to_string())
        .collect();
    lock.replaced.retain(|old, _| !current_ids.contains(old));
    lock.displaced.retain(|old, _| !current_ids.contains(old));
    write_if_changed(&config.lock, &render_lock(&lock))?;
    let newly_replaced = lock
        .replaced
        .keys()
        .filter(|old| !old_lock.replaced.contains_key(*old))
        .count();

    let module = module_for(&scan.sources, &lock).expect("every file has a lockfile entry");
    report.module_written = write_if_changed(&config.output, &module)?;
    writeln!(
        out,
        "{} uploaded, {} file(s) in total. {output} {}.",
        report.uploaded.len(),
        plan.items.len(),
        if report.module_written {
            "was updated"
        } else {
            "is up to date"
        }
    )?;
    if newly_replaced > 0 {
        writeln!(
            out,
            "{newly_replaced} asset id(s) of the previous creator were replaced and recorded in \
             {}. Run `rojo assets remap` to find code still using the old ids.",
            display_path(&config, &config.lock)
        )?;
    }
    Ok(report)
}

/// Sets `entry` as the lockfile entry for `source`, recording the old ids it
/// replaces. An overwritten entry of another creator whose contents still
/// exist at another path is not replaced by `entry`, so it moves to
/// `displaced` until that path's upload records it, in the same lockfile
/// write as this entry.
fn replace_entry(
    lock: &mut LockFile,
    old_lock: &LockFile,
    current_hashes: &HashSet<&str>,
    source: &Source,
    entry: LockEntry,
    predecessor: Option<&LockEntry>,
) {
    record_replacements(lock, old_lock, current_hashes, source, &entry, predecessor);
    // A held id that is in use again is no longer held.
    lock.displaced.remove(&entry.asset_id.to_string());
    if let Some(previous) = lock.assets.get(&source.rel) {
        let recorded = lock.replaced.contains_key(&previous.asset_id.to_string());
        let claim = lock.pending.values().find(|pending| {
            pending
                .replaces
                .as_ref()
                .is_some_and(|replaces| replaces.asset_id == previous.asset_id)
        });
        if let Some(claim) = claim
            .filter(|_| previous.creator != entry.creator && previous.asset_id != entry.asset_id)
        {
            // An unfinished upload claims this entry as the one it replaces,
            // so it is held for that upload rather than dropped with the
            // overwrite, whatever this upload's contents are.
            let successor_hash = claim.hash.clone();
            lock.displaced.insert(
                previous.asset_id.to_string(),
                HeldEntry {
                    entry: previous.clone(),
                    successor_hash: Some(successor_hash),
                },
            );
        } else if previous.creator != entry.creator
            && previous.asset_id != entry.asset_id
            && previous.hash != source.hash
            && current_hashes.contains(previous.hash.as_str())
            && !recorded
        {
            lock.displaced.insert(
                previous.asset_id.to_string(),
                HeldEntry::new(previous.clone()),
            );
        }
    }
    lock.assets.insert(source.rel.clone(), entry);
}

/// Whether an upload of `source` may claim `previous`, the entry at its path,
/// as the one it replaces. Not when `previous`'s contents still exist at
/// another scanned path: its id follows those contents, as it would if the
/// sync were not interrupted, since a claim is authoritative once made.
fn may_claim(previous: &LockEntry, source: &Source, current_hashes: &HashSet<&str>) -> bool {
    previous.hash == source.hash || !current_hashes.contains(previous.hash.as_str())
}

/// Whether an unfinished upload claims the entry with `asset_id`.
fn is_claimed(lock: &LockFile, asset_id: u64) -> bool {
    lock.pending.values().any(|pending| {
        pending
            .replaces
            .as_ref()
            .is_some_and(|replaces| replaces.asset_id == asset_id)
    })
}

/// Records which old ids `entry`, the new lockfile entry for `source`,
/// replaces because the creator changed: the previous entry at the same path,
/// and any previous entry with the same contents. Entries of the same creator
/// are never recorded, since a changed file for the same creator is a new
/// asset, not a move, and code using its old id may mean the old contents.
///
/// `predecessor` is the entry a resumed upload's pending record says it
/// replaces, which counts like the entry at the upload's own path. Entries
/// that another pending upload claims are left to that upload, so a fresh
/// upload at a path never takes an id that an unfinished upload replaces.
fn record_replacements(
    lock: &mut LockFile,
    old_lock: &LockFile,
    current_hashes: &HashSet<&str>,
    source: &Source,
    entry: &LockEntry,
    predecessor: Option<&LockEntry>,
) {
    let replaceable = |old: &LockEntry| {
        old.creator != entry.creator
            && old.asset_type == entry.asset_type
            && old.asset_id != entry.asset_id
    };
    // Claims are the lineage: the entry an upload recorded as the one it
    // replaces when it was sent (its pending record's `replaces`, or a held
    // entry released for these contents) goes to this upload, whatever
    // the contents or paths look like now.
    let held_for_these: Vec<&LockEntry> = old_lock
        .displaced
        .values()
        .filter(|held| held.successor_hash.as_deref() == Some(source.hash.as_str()))
        .map(|held| &held.entry)
        .collect();
    let explicit: BTreeSet<u64> = predecessor
        .into_iter()
        .chain(held_for_these)
        .filter(|old| replaceable(old))
        .map(|old| old.asset_id)
        .collect();
    // Ids other uploads claim, by a pending record (an upload's own record
    // is removed once it finishes) or a held entry waiting for other
    // contents, are left to those uploads.
    let claimed: BTreeSet<u64> = lock
        .pending
        .values()
        .filter_map(|pending| pending.replaces.as_ref())
        .map(|replaces| replaces.asset_id)
        .chain(
            old_lock
                .displaced
                .values()
                .chain(lock.displaced.values())
                .filter(|held| held.successor_hash.is_some())
                .map(|held| held.entry.asset_id),
        )
        .collect();
    // Inferred from paths and contents. Held entries without a claim have no
    // path any more, so they are only found by contents. An id that an
    // earlier upload for this creator already resolved keeps that mapping,
    // so the order files are processed in does not decide it.
    let inferred = old_lock
        .assets
        .iter()
        .map(|(rel, old)| (Some(rel), old))
        .chain(
            old_lock
                .displaced
                .values()
                .filter(|held| held.successor_hash.is_none())
                .map(|held| (None, &held.entry)),
        )
        .filter(|(rel, old)| {
            replaceable(old)
                && !claimed.contains(&old.asset_id)
                && !lock
                    .replaced
                    .get(&old.asset_id.to_string())
                    .is_some_and(|replaced| replaced.to_creator == entry.creator)
                && (old.hash == source.hash
                    // When the old contents still exist at another path,
                    // their id moves with them rather than to whatever
                    // now sits at this path.
                    || (*rel == Some(&source.rel)
                        && !current_hashes.contains(old.hash.as_str())))
        })
        .map(|(_, old)| old.asset_id);
    let old_ids: BTreeSet<u64> = explicit.iter().copied().chain(inferred).collect();
    for old_id in old_ids {
        let key = old_id.to_string();
        // Recorded now, so it no longer needs holding.
        lock.displaced.remove(&key);
        if lock
            .replaced
            .get(&key)
            .is_some_and(|replaced| replaced.new_asset_id == entry.asset_id)
        {
            continue;
        }
        let from_creator = predecessor
            .into_iter()
            .chain(old_lock.assets.values())
            .chain(old_lock.displaced.values().map(|held| &held.entry))
            .find(|old| old.asset_id == old_id)
            .map(|old| old.creator.clone())
            .unwrap_or_default();
        // Ids that earlier creator changes replaced with `old_id` now resolve
        // straight to the newest id.
        for replaced in lock.replaced.values_mut() {
            if replaced.new_asset_id == old_id {
                replaced.new_asset_id = entry.asset_id;
                replaced.to_creator = entry.creator.clone();
            }
        }
        lock.replaced.insert(
            key,
            ReplacedAsset {
                new_asset_id: entry.asset_id,
                path: source.rel.clone(),
                asset_type: entry.asset_type.clone(),
                from_creator,
                to_creator: entry.creator.clone(),
                replaced: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
            },
        );
        // Switching back to an earlier creator can make an old id current
        // again; it must not be remapped, or it would point at itself.
        lock.replaced.remove(&entry.asset_id.to_string());
        lock.displaced.remove(&entry.asset_id.to_string());
    }
}

/// Uploads one file, or finishes the earlier upload `resume` names, and
/// returns its lockfile entry. Fails when Roblox rejects it in moderation,
/// since its id would not load.
///
/// Once Roblox has accepted the file, the operation is written to `lock`'s
/// `pending` (and to disk) before polling, so an upload that cannot be
/// followed to the end is resumed by the next run rather than repeated. On
/// success the pending entry is removed from `lock`, and the caller writes
/// it together with the new asset entry.
fn upload(
    client: &OpenCloud,
    config: &Config,
    source: &Source,
    resume: Option<&Resume>,
    creator: &str,
    current_hashes: &HashSet<&str>,
    lock: &mut LockFile,
) -> anyhow::Result<LockEntry> {
    let (key, operation, result) = match resume {
        Some(resume) => (
            resume.key.clone(),
            resume.operation.clone(),
            client.resume_asset_upload(&resume.operation),
        ),
        None => {
            let started = start_upload(client, config, source)?;
            let operation = started.operation.clone();
            let key = pending_key(source.kind.name(), creator, &source.hash);
            // `plan` resumes a pending upload of these contents rather than
            // sending them again, so this never replaces another operation.
            debug_assert!(!lock.pending.contains_key(&key));
            // What this upload replaces, unless another unfinished upload
            // already claims it or its id belongs to its contents elsewhere.
            let replaces = lock
                .assets
                .get(&source.rel)
                .filter(|previous| {
                    previous.creator != creator
                        && may_claim(previous, source, current_hashes)
                        && !is_claimed(lock, previous.asset_id)
                })
                .cloned();
            lock.pending.insert(
                key.clone(),
                PendingUpload {
                    path: source.rel.clone(),
                    hash: source.hash.clone(),
                    asset_type: source.kind.name().to_owned(),
                    creator: creator.to_owned(),
                    operation: operation.clone(),
                    started: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
                    replaces,
                },
            );
            write_atomic(&config.lock, render_lock(lock)).with_context(|| {
                format!(
                    "Roblox accepted the upload of {} as {operation}, but it could not be \
                     recorded; check the creator's assets before running sync again, since a \
                     rerun uploads the file again",
                    source.rel
                )
            })?;
            (key, operation, client.finish_asset_upload(started))
        }
    };
    let (uploaded, finished) = match result {
        Ok(uploaded) => (uploaded, lock.pending.remove(&key)),
        // Roblox finished the operation and created nothing, so the next
        // run should send the file again. What it was replacing is held
        // for that upload.
        Err(error @ OpenCloudError::Failed(_)) => {
            if let Some(pending) = lock.pending.remove(&key) {
                release_claim(lock, pending);
            }
            write_atomic(&config.lock, render_lock(lock))?;
            bail!("Could not upload {}: {error}.", source.rel);
        }
        Err(error) => bail!(
            "Could not finish uploading {}: {error}. Roblox accepted the file as {operation}, \
             which is recorded in {}; the next `rojo assets sync` checks on it instead of \
             uploading the file again. If that keeps failing, check the creator's assets, \
             then remove the entry {key} under \"pending\" in the lockfile to upload it \
             again.",
            source.rel,
            display_path(config, &config.lock)
        ),
    };
    if uploaded.moderation_state.as_deref() == Some("Rejected") {
        // Recorded so that later runs do not send the same contents again.
        lock.rejected.insert(
            source.hash.clone(),
            RejectedUpload {
                path: source.rel.clone(),
                asset_id: uploaded.asset_id,
                asset_type: source.kind.name().to_owned(),
                creator: creator.to_owned(),
                rejected: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
            },
        );
        // The rejected id is never used, so what this upload was replacing
        // is held: a retry of these contents with --retry-rejected still
        // records it, and otherwise the next finishing sync drops it.
        if let Some(pending) = finished {
            release_claim(lock, pending);
        }
        write_atomic(&config.lock, render_lock(lock))?;
        bail!(
            "Roblox rejected {} in moderation (asset {}). The rejection is recorded in {}, so \
             later syncs do not upload these contents again; replace the file and sync again, \
             or pass --retry-rejected.",
            source.rel,
            uploaded.asset_id,
            display_path(config, &config.lock)
        );
    }
    Ok(LockEntry {
        hash: source.hash.clone(),
        asset_id: uploaded.asset_id,
        asset_type: source.kind.name().to_owned(),
        creator: creator.to_owned(),
        moderation_state: uploaded.moderation_state,
        uploaded: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
    })
}

/// Reads the file again, checks that it did not change since the scan and
/// sends it.
fn start_upload(
    client: &OpenCloud,
    config: &Config,
    source: &Source,
) -> anyhow::Result<StartedUpload> {
    let bytes =
        fs::read(&source.path).with_context(|| format!("Cannot read {}", source.path.display()))?;
    if blake3::hash(&bytes).to_hex().as_str() != source.hash {
        bail!(
            "{} changed while syncing; run `rojo assets sync` again",
            source.rel
        );
    }
    let stem = source
        .rel
        .rsplit_once('.')
        .map_or(source.rel.as_str(), |(stem, _)| stem);
    let display_name: String = format!("{}{}", config.name_prefix, stem.replace('/', "."))
        .chars()
        .take(MAX_DISPLAY_NAME_CHARS)
        .collect();
    let description = config
        .description
        .clone()
        .unwrap_or_else(|| format!("Uploaded by rojo assets sync from {}", source.rel));
    let description: String = description.chars().take(MAX_DESCRIPTION_CHARS).collect();
    // The name only labels the upload, so characters that cannot go in a
    // multipart header are replaced instead of failing the upload.
    let file_name: String = source
        .rel
        .rsplit('/')
        .next()
        .unwrap_or(&source.rel)
        .chars()
        .map(|c| {
            if c == '"' || c == '\\' || c.is_control() {
                '_'
            } else {
                c
            }
        })
        .collect();

    client
        .start_asset_upload(
            source.kind.asset_type(),
            &display_name,
            &description,
            config.creator,
            &file_name,
            source.content_type,
            &bytes,
        )
        .map_err(|error| {
            // Without an operation there is nothing to resume.
            let hint = if error.may_have_applied() {
                " Roblox may still have created the asset; check the creator's assets before \
                 running sync again, since a rerun uploads the file again."
            } else {
                ""
            };
            anyhow::anyhow!("Could not upload {}: {error}.{hint}", source.rel)
        })
}

/// File extensions `remap` reads when it walks a folder: the text formats
/// that hold asset ids in Rojo projects, including XML models and places.
/// Files named on the command line are read whatever their extension.
const REMAP_EXTENSIONS: &[&str] = &[
    "lua", "luau", "json", "toml", "csv", "tsv", "txt", "md", "yaml", "yml", "xml", "rbxmx",
    "rbxlx", "html",
];

/// Folders `remap` does not walk into: installed packages belong to other
/// projects and are replaced on the next install, and `target` is build
/// output. Hidden folders such as `.git` are skipped too.
const REMAP_SKIPPED_DIRS: &[&str] = &[
    "node_modules",
    "Packages",
    "ServerPackages",
    "DevPackages",
    "target",
];

/// How far back from `id=` a URL is looked for, so that a long line without
/// spaces cannot make every match scan the whole file.
const MAX_URL_BYTES: usize = 2048;

#[derive(Debug, Default)]
struct RemapOptions {
    /// Absolute, normalized files or folders. Empty for the config's folder.
    paths: Vec<PathBuf>,
    write: bool,
    bare: bool,
    /// Absolute, normalized.
    map_out: Option<PathBuf>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
enum ReferenceKind {
    /// `rbxassetid://<id>`.
    AssetId,
    /// A Roblox asset URL such as `https://www.roblox.com/asset/?id=<id>`,
    /// or an `rbxthumb://` URI.
    Url,
    /// A number on its own, only matched with `--bare`.
    Bare,
}

#[derive(Debug, Clone, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
struct Reference {
    path: String,
    line: usize,
    kind: ReferenceKind,
    old_id: u64,
    new_id: u64,
}

/// What a remap found and did. Also the `--json` output.
#[derive(Debug, Default, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
struct RemapReport {
    write: bool,
    lockfile: String,
    /// Old ids recorded in the lockfile.
    replacements: usize,
    files_scanned: usize,
    references: Vec<Reference>,
    files_with_references: usize,
    references_rewritten: usize,
    files_rewritten: usize,
    /// Bare numbers equal to an old id, left alone because `--bare` was not
    /// given.
    bare_skipped: usize,
    /// Files with references that changed on disk between being read and
    /// being rewritten, such as an editor saving them. They are left as they
    /// are, so the other edit is kept; running remap again picks them up.
    changed_during_remap: Vec<String>,
    /// Old ids recorded under `replaced` that an entry under `assets` still
    /// uses, so they are current and are not rewritten. `sync` drops such
    /// records; these come from a lockfile edited or merged by hand.
    live_ids_skipped: Vec<u64>,
    /// Files with references that are symbolic links and so were not
    /// rewritten: the atomic write renames a new file over the path, which
    /// would replace the link with a regular file. Their targets need to be
    /// edited directly.
    symlinks_skipped: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    map_out: Option<String>,
}

/// Each old id under `replaced` with the newest id it leads to. Records are
/// pointed at the newest id when they are written, but following the chain
/// here also covers a lockfile merged from branches that both moved assets.
fn resolve_replacements(lock: &LockFile, lock_path: &Path) -> anyhow::Result<BTreeMap<u64, u64>> {
    let mut map = BTreeMap::new();
    for (old, replaced) in &lock.replaced {
        let old_id: u64 = old.parse().map_err(|_| {
            anyhow::anyhow!(
                "{}: {old:?} under \"replaced\" is not an asset id",
                lock_path.display()
            )
        })?;
        if old_id == 0 {
            bail!(
                "{}: \"0\" under \"replaced\" is not an asset id; fix or remove that record \
                 before remapping",
                lock_path.display()
            );
        }
        // A cycle, such as 123 -> 456 -> 123 from a bad merge or edit, has
        // no newest id: accepting wherever the walk stops would swap ids on
        // every run. So the whole mapping is refused before anything is read
        // or written.
        let mut chain = vec![old_id];
        let mut new_id = replaced.new_asset_id;
        loop {
            if new_id == 0 {
                bail!(
                    "{}: the record for {} under \"replaced\" leads to the asset id 0, which \
                     is not an asset id; fix or remove it before remapping",
                    lock_path.display(),
                    chain.last().copied().unwrap_or(old_id)
                );
            }
            if chain.contains(&new_id) {
                chain.push(new_id);
                let ids: Vec<String> = chain.iter().map(u64::to_string).collect();
                bail!(
                    "{}: the records under \"replaced\" form a cycle ({}), so there is no \
                     newest id to remap to. Fix or remove those records; nothing was written.",
                    lock_path.display(),
                    ids.join(" -> ")
                );
            }
            chain.push(new_id);
            match lock.replaced.get(&new_id.to_string()) {
                Some(next) => new_id = next.new_asset_id,
                None => break,
            }
        }
        map.insert(old_id, new_id);
    }
    Ok(map)
}

/// The `--map-out` file: a JSON object from old id to new id, in id order.
fn render_id_map(map: &BTreeMap<u64, u64>) -> String {
    if map.is_empty() {
        return "{}\n".to_owned();
    }
    let lines: Vec<String> = map
        .iter()
        .map(|(old, new)| format!("  \"{old}\": {new}"))
        .collect();
    format!("{{\n{}\n}}\n", lines.join(",\n"))
}

/// A reference found in a file, as a byte range of the id's digits.
struct Found {
    start: usize,
    end: usize,
    line: usize,
    kind: ReferenceKind,
    old_id: u64,
    new_id: u64,
}

/// Finds every id in `map` in `text`. Works on bytes, so files that are not
/// valid UTF-8 are read too and everything but the ids stays byte for byte.
fn find_references(text: &[u8], map: &BTreeMap<u64, u64>) -> Vec<Found> {
    let mut found = Vec::new();
    let mut line = 1;
    let mut at = 0;
    while at < text.len() {
        let byte = text[at];
        if byte == b'\n' {
            line += 1;
        }
        if !byte.is_ascii_digit() {
            at += 1;
            continue;
        }
        // Only the first digit of a run gets here, so the run is the whole
        // number and 123 never matches inside 1234.
        let start = at;
        while at < text.len() && text[at].is_ascii_digit() {
            at += 1;
        }
        let end = at;
        // Asset ids have no leading zeros.
        if text[start] == b'0' {
            continue;
        }
        let Some(old_id) = std::str::from_utf8(&text[start..end])
            .ok()
            .and_then(|digits| digits.parse::<u64>().ok())
        else {
            continue;
        };
        let Some(&new_id) = map.get(&old_id) else {
            continue;
        };
        let before = &text[..start];
        let kind = if ends_with_ignore_case(before, b"rbxassetid://") {
            ReferenceKind::AssetId
        } else if is_asset_url(text, start, end) {
            ReferenceKind::Url
        } else if is_bare_number(text, start, end) {
            ReferenceKind::Bare
        } else {
            continue;
        };
        found.push(Found {
            start,
            end,
            line,
            kind,
            old_id,
            new_id,
        });
    }
    found
}

fn ends_with_ignore_case(text: &[u8], suffix: &[u8]) -> bool {
    text.len() >= suffix.len() && text[text.len() - suffix.len()..].eq_ignore_ascii_case(suffix)
}

/// Hosts whose `/asset` URLs take an asset id. Matched exactly, so that
/// look-alikes such as `notroblox.com` or `roblox.com.example.com` are left
/// alone.
const ASSET_URL_HOSTS: &[&str] = &["roblox.com", "www.roblox.com", "assetdelivery.roblox.com"];

/// Paths of those hosts that take `id=<asset id>` in their query.
const ASSET_URL_PATHS: &[&str] = &["/asset", "/asset/", "/v1/asset", "/v1/asset/"];

fn is_url_delimiter(byte: u8) -> bool {
    byte.is_ascii_whitespace()
        || matches!(
            byte,
            b'"' | b'\'' | b'`' | b'(' | b')' | b'<' | b'>' | b'[' | b']'
        )
}

/// How XML writes `&`. Only used to read URLs; the file keeps its bytes.
const XML_AMPERSANDS: &[&str] = &["&amp;", "&#38;", "&#x26;"];

/// `bytes` lowercased, with XML-escaped ampersands read as `&`.
fn unescape_ampersands(bytes: &[u8]) -> String {
    let mut text = String::from_utf8_lossy(bytes).to_ascii_lowercase();
    for entity in XML_AMPERSANDS {
        text = text.replace(entity, "&");
    }
    text
}

/// Whether `a` and `b` name the same file, comparing their canonical
/// folders and file names, since the file itself may not exist yet. Windows
/// file names are case-insensitive, so they are compared that way there.
fn is_same_file_path(a: &Path, b: &Path) -> bool {
    if let (Ok(a), Ok(b)) = (fs::canonicalize(a), fs::canonicalize(b)) {
        if a == b {
            return true;
        }
    }
    let key = |path: &Path| -> Option<(String, String)> {
        let name = path.file_name()?.to_string_lossy().into_owned();
        let parent = path
            .parent()
            .filter(|parent| !parent.as_os_str().is_empty())
            .unwrap_or(Path::new("."));
        let parent = fs::canonicalize(parent).unwrap_or_else(|_| normalize(parent));
        let parent = parent.to_string_lossy().into_owned();
        Some(if cfg!(windows) {
            (parent.to_lowercase(), name.to_lowercase())
        } else {
            (parent, name)
        })
    };
    matches!((key(a), key(b)), (Some(a), Some(b)) if a == b)
}

/// Whether the digits at `start..end` are the `id=` query parameter of a
/// Roblox asset URL, such as `https://www.roblox.com/asset/?id=` or
/// `https://assetdelivery.roblox.com/v1/asset/?id=`, or of an
/// `rbxthumb://type=Asset&id=` URI. Thumbnails of other types, such as
/// `Avatar` or `GameIcon`, take user or universe ids and are left alone.
fn is_asset_url(text: &[u8], start: usize, end: usize) -> bool {
    let before = &text[..start];
    if !ends_with_ignore_case(before, b"id=") {
        return false;
    }
    let rest = &before[..before.len() - 3];
    // `rbxthumb://` URIs have no `?`, so their first parameter follows the
    // scheme directly. XML files, such as .rbxmx models, write `&` as an
    // entity.
    if !matches!(rest.last(), Some(b'?' | b'&'))
        && !XML_AMPERSANDS
            .iter()
            .any(|entity| ends_with_ignore_case(rest, entity.as_bytes()))
        && !ends_with_ignore_case(rest, b"rbxthumb://")
    {
        return false;
    }
    let window = &rest[rest.len().saturating_sub(MAX_URL_BYTES)..];
    // The URL starts after the nearest character that cannot be in one.
    let url_start = window
        .iter()
        .rposition(|byte| is_url_delimiter(*byte))
        .map_or(0, |position| position + 1);
    let url = unescape_ampersands(&window[url_start..]);

    if let Some(params) = url.strip_prefix("rbxthumb://") {
        // `type` may come after the id, so the rest of the URI is read too.
        let after = &text[end..text.len().min(end + MAX_URL_BYTES)];
        let after_end = after
            .iter()
            .position(|byte| is_url_delimiter(*byte))
            .unwrap_or(after.len());
        let after = unescape_ampersands(&after[..after_end]);
        return params
            .split('&')
            .chain(after.split('&'))
            .any(|param| param == "type=asset");
    }

    let Some(after_scheme) = url
        .strip_prefix("https://")
        .or_else(|| url.strip_prefix("http://"))
    else {
        return false;
    };
    let authority_end = after_scheme
        .find(['/', '?', '#'])
        .unwrap_or(after_scheme.len());
    let (host, path_and_query) = after_scheme.split_at(authority_end);
    // `rest` ends just before `id=`, so this is the path and the earlier
    // query parameters, ending in `?` or `&`.
    let Some((path, _query)) = path_and_query.split_once('?') else {
        return false;
    };
    ASSET_URL_HOSTS.contains(&host)
        && ASSET_URL_PATHS.contains(&path)
        && !path_and_query.contains('#')
}
/// Whether the digits at `start..end` are a complete integer token rather
/// than part of a word (`id123`, `x123_`), a hexadecimal or exponent
/// (`0x123`, `123e3`, `1e123`, `1e-123`, `1E+123`), a decimal or version
/// (`.5`, `1.5`, `123.`, `1.2.3`) or a signed number (`-123`, `+123`). A `.`
/// on either side rules it out, even at the end of a sentence, and so does a
/// sign directly before the digits, since asset ids are positive and never
/// written with one: rewriting part of a number would silently change it.
/// A sign separated by a space, as in `x - 123`, is an operator, so that
/// number still counts.
fn is_bare_number(text: &[u8], start: usize, end: usize) -> bool {
    let joins = |byte: u8| byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'.';
    let before = start.checked_sub(1).map(|index| text[index]);
    let after = text.get(end).copied();
    !before.is_some_and(|byte| joins(byte) || byte == b'-' || byte == b'+')
        && !after.is_some_and(joins)
}
/// Lists the files `remap` reads under `roots`, in a stable order.
fn remap_files(roots: &[PathBuf], skipped: &[PathBuf]) -> anyhow::Result<BTreeSet<PathBuf>> {
    let mut files = BTreeSet::new();
    for root in roots {
        let metadata = match fs::metadata(root) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                return Err(UsageError(anyhow::anyhow!("{} does not exist", root.display())).into())
            }
            Err(error) => {
                return Err(error).with_context(|| format!("Cannot read {}", root.display()))
            }
        };
        if metadata.is_dir() {
            walk_text(root, &mut files)?;
        } else {
            files.insert(root.clone());
        }
    }
    // Lockfiles of every config are skipped, not only this one's: their ids
    // are records of past uploads, and with --bare they would be rewritten.
    files.retain(|path| {
        // Compared by physical identity, not spelling: on Windows a path in
        // another case, or through `sub/..` or a link, is the same file, and
        // `--bare --write` must never rewrite the config or the module.
        !skipped
            .iter()
            .any(|skipped| is_same_file_path(path, skipped))
            && !path
                .file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.to_ascii_lowercase().ends_with(".lock.json"))
    });
    Ok(files)
}

fn walk_text(dir: &Path, files: &mut BTreeSet<PathBuf>) -> anyhow::Result<()> {
    let entries = fs::read_dir(dir).with_context(|| format!("Cannot list {}", dir.display()))?;
    for entry in entries {
        let entry = entry.with_context(|| format!("Cannot list {}", dir.display()))?;
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if name.starts_with('.') {
            continue;
        }
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            if !REMAP_SKIPPED_DIRS.contains(&name.as_ref()) {
                walk_text(&path, files)?;
            }
        } else if (file_type.is_file() || (file_type.is_symlink() && path.is_file()))
            && path
                .extension()
                .and_then(|extension| extension.to_str())
                .is_some_and(|extension| {
                    REMAP_EXTENSIONS.contains(&extension.to_ascii_lowercase().as_str())
                })
        {
            files.insert(path);
        }
    }
    Ok(())
}

/// Finds references to the old ids recorded under `replaced`, and rewrites
/// them with `write`.
fn remap(config_path: &Path, options: &RemapOptions) -> anyhow::Result<RemapReport> {
    remap_with(config_path, options, &mut |_| {})
}

/// `remap`, calling `before_write` with each file just before it is checked
/// again and rewritten, so tests can change a file at that moment.
fn remap_with(
    config_path: &Path,
    options: &RemapOptions,
    before_write: &mut dyn FnMut(&Path),
) -> anyhow::Result<RemapReport> {
    let config = load_config(config_path)?;
    let lock_path = normalize(&config.lock);
    // `--map-out` is written even without `--write`, so a mistyped path must
    // not replace a file that sync depends on.
    if let Some(map_out) = &options.map_out {
        let protected = [
            (&config.config, "the assets config"),
            (&lock_path, "the assets lockfile"),
            (&config.output, "the module sync generates"),
        ];
        for (path, what) in protected {
            if is_same_file_path(map_out, path) {
                return Err(UsageError(anyhow::anyhow!(
                    "--map-out {} is {what}; choose another file. Nothing was written.",
                    map_out.display()
                ))
                .into());
            }
        }
    }
    let mut lock = load_lock(&lock_path)?;
    // Records for ids still in use are left out before chains are followed,
    // so that a chain ends at a live id instead of passing through it.
    let live_ids: BTreeSet<String> = lock
        .assets
        .values()
        .map(|entry| entry.asset_id.to_string())
        .collect();
    let live_ids_skipped: Vec<u64> = lock
        .replaced
        .keys()
        .filter(|old| live_ids.contains(*old))
        .filter_map(|old| old.parse().ok())
        .collect();
    lock.replaced.retain(|old, _| !live_ids.contains(old));
    let map = resolve_replacements(&lock, &lock_path)?;
    let mut report = RemapReport {
        write: options.write,
        lockfile: display_path(&config, &lock_path),
        replacements: map.len(),
        live_ids_skipped,
        ..RemapReport::default()
    };

    if !map.is_empty() {
        let roots = if options.paths.is_empty() {
            vec![config
                .config
                .parent()
                .map_or_else(|| PathBuf::from("."), Path::to_path_buf)]
        } else {
            options.paths.clone()
        };
        // Files Rojo writes from the lockfile, which hold new ids already or
        // must keep the old ones, and the config, which holds no asset ids.
        let mut skipped = vec![
            lock_path.clone(),
            config.output.clone(),
            config.config.clone(),
        ];
        skipped.extend(options.map_out.iter().cloned());
        for path in remap_files(&roots, &skipped)? {
            let text =
                fs::read(&path).with_context(|| format!("Cannot read {}", path.display()))?;
            report.files_scanned += 1;
            let (found, bare): (Vec<Found>, Vec<Found>) = find_references(&text, &map)
                .into_iter()
                .partition(|found| options.bare || found.kind != ReferenceKind::Bare);
            report.bare_skipped += bare.len();
            if found.is_empty() {
                continue;
            }
            report.files_with_references += 1;
            let rel = display_path(&config, &path);
            report
                .references
                .extend(found.iter().map(|found| Reference {
                    path: rel.clone(),
                    line: found.line,
                    kind: found.kind,
                    old_id: found.old_id,
                    new_id: found.new_id,
                }));
            if options.write {
                let mut rewritten = Vec::with_capacity(text.len());
                let mut at = 0;
                for found in &found {
                    rewritten.extend_from_slice(&text[at..found.start]);
                    rewritten.extend_from_slice(found.new_id.to_string().as_bytes());
                    at = found.end;
                }
                rewritten.extend_from_slice(&text[at..]);
                before_write(&path);
                if fs::symlink_metadata(&path)
                    .is_ok_and(|metadata| metadata.file_type().is_symlink())
                {
                    report.symlinks_skipped.push(rel);
                    continue;
                }
                // The replacement was computed from `text`, so writing it over
                // a file that changed since would throw away that change. A
                // save between this check and the rename can still be lost;
                // closing that gap would need file locking that editors do
                // not honour, and the window is a few milliseconds.
                if fs::read(&path).ok().as_deref() != Some(text.as_slice()) {
                    report.changed_during_remap.push(rel);
                    continue;
                }
                write_atomic(&path, &rewritten)?;
                report.files_rewritten += 1;
                report.references_rewritten += found.len();
            }
        }
    }

    if let Some(map_out) = &options.map_out {
        write_atomic(map_out, render_id_map(&map))?;
        report.map_out = Some(display_path(&config, map_out));
    }
    Ok(report)
}

fn describe_remap(report: &RemapReport, out: &mut dyn Write) -> io::Result<()> {
    for reference in &report.references {
        writeln!(
            out,
            "  {}:{}  {} -> {}{}",
            reference.path,
            reference.line,
            reference.old_id,
            reference.new_id,
            if reference.kind == ReferenceKind::Bare {
                " (bare number)"
            } else {
                ""
            }
        )?;
    }
    if !report.live_ids_skipped.is_empty() {
        let ids: Vec<String> = report.live_ids_skipped.iter().map(u64::to_string).collect();
        writeln!(
            out,
            "warning: {} under \"replaced\" in {} {} still used under \"assets\", so {} not \
             rewritten. Run `rojo assets sync` to drop such records, or remove them by hand.",
            ids.join(", "),
            report.lockfile,
            if ids.len() == 1 { "is" } else { "are" },
            if ids.len() == 1 { "it is" } else { "they are" },
        )?;
    }
    if report.replacements == 0 {
        writeln!(
            out,
            "No replaced asset ids are recorded in {}; there is nothing to remap.",
            report.lockfile
        )?;
    } else {
        writeln!(
            out,
            "Scanned {} file(s) for {} replaced id(s): {} reference(s) in {} file(s).",
            report.files_scanned,
            report.replacements,
            report.references.len(),
            report.files_with_references
        )?;
        if report.write {
            writeln!(
                out,
                "Rewrote {} reference(s) in {} file(s).",
                report.references_rewritten, report.files_rewritten
            )?;
            if !report.changed_during_remap.is_empty() {
                writeln!(
                    out,
                    "Not rewritten, because they changed while remap ran: {}. Run `rojo assets \
                     remap --write` again to update them.",
                    report.changed_during_remap.join(", ")
                )?;
            }
            if !report.symlinks_skipped.is_empty() {
                writeln!(
                    out,
                    "Not rewritten because they are symbolic links: {}; edit their targets \
                     directly.",
                    report.symlinks_skipped.join(", ")
                )?;
            }
        } else if !report.references.is_empty() {
            writeln!(
                out,
                "Nothing was written; run again with --write to rewrite them."
            )?;
        }
        if report.bare_skipped > 0 {
            writeln!(
                out,
                "{} bare number(s) equal to an old id were left alone; pass --bare to list \
                 them, and --bare --write to rewrite them too.",
                report.bare_skipped
            )?;
        }
    }
    if let Some(map_out) = &report.map_out {
        writeln!(
            out,
            "Wrote {} id mapping(s) to {map_out}.",
            report.replacements
        )?;
    }
    Ok(())
}

