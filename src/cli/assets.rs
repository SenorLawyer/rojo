/// The config file used when `--config` is not given.
const DEFAULT_CONFIG: &str = "assets.toml";

/// The lockfile format this build reads and writes. Builds refuse lockfiles
/// with any other version instead of rewriting them, so bump this when adding
/// a field that an older build must not silently drop.
const LOCK_VERSION: u32 = 1;

/// Open Cloud's per-request limit for asset files.
const MAX_FILE_BYTES: u64 = 20 * 1024 * 1024;

/// Images must be smaller than this many pixels on each side.
const MAX_IMAGE_SIDE: u32 = 8000;

/// Open Cloud's limits for `displayName` and `description`.
const MAX_DISPLAY_NAME_CHARS: usize = 50;
const MAX_DESCRIPTION_CHARS: usize = 1000;

const MODULE_HEADER: &str = "--!strict\n-- Generated by rojo assets sync; do not edit.\n";

/// Uploads images, audio and models through Open Cloud and writes a Luau
/// module of their asset ids. See docs/assets.md.
#[derive(Debug, Parser)]
pub struct AssetsCommand {
    #[clap(subcommand)]
    subcommand: AssetsSubcommand,
}

#[derive(Debug, Parser)]
enum AssetsSubcommand {
    /// Upload new and changed files, then update the lockfile and the module.
    Sync {
        /// Path to the assets config.
        #[clap(long, default_value = DEFAULT_CONFIG)]
        config: PathBuf,
        /// List what would be uploaded without uploading or writing anything.
        #[clap(long)]
        dry_run: bool,
        /// Environment variable holding the Open Cloud API key. Only read when
        /// something needs uploading.
        #[clap(long, default_value = DEFAULT_API_KEY_VAR)]
        api_key_env: String,
        /// Upload files again whose exact contents Roblox rejected in
        /// moderation before. Without it such files stop the sync.
        #[clap(long)]
        retry_rejected: bool,
    },
    /// Show which files are new, changed, renamed or missing, without network
    /// access.
    Status {
        /// Path to the assets config.
        #[clap(long, default_value = DEFAULT_CONFIG)]
        config: PathBuf,
    },
}

impl AssetsCommand {
    pub fn run(self) -> anyhow::Result<()> {
        let stdout = io::stdout();
        let mut out = stdout.lock();
        match self.subcommand {
            AssetsSubcommand::Sync {
                config,
                dry_run,
                api_key_env,
                retry_rejected,
            } => {
                let config = resolve_path(&config)?;
                sync(
                    &config,
                    SyncOptions {
                        dry_run,
                        retry_rejected,
                    },
                    || OpenCloud::from_env(&api_key_env),
                    &mut out,
                )?;
            }
            AssetsSubcommand::Status { config } => {
                let config = resolve_path(&config)?;
                status(&config, &mut out)?;
            }
        }
        Ok(())
    }
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct ConfigFile {
    /// Folder holding the assets, relative to the config.
    source: PathBuf,
    /// Luau module to write, relative to the config.
    output: PathBuf,
    creator: CreatorConfig,
    #[serde(default)]
    name_prefix: String,
    #[serde(default)]
    description: Option<String>,
    #[serde(default)]
    include: Vec<String>,
    #[serde(default)]
    exclude: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct CreatorConfig {
    user_id: Option<u64>,
    group_id: Option<u64>,
}

/// A loaded config with its paths made absolute.
struct Config {
    source: PathBuf,
    output: PathBuf,
    lock: PathBuf,
    config: PathBuf,
    creator: Creator,
    name_prefix: String,
    description: Option<String>,
    include: Option<GlobSet>,
    exclude: Option<GlobSet>,
}

impl Config {
    fn creator_key(&self) -> String {
        match self.creator {
            Creator::User(id) => format!("user:{id}"),
            Creator::Group(id) => format!("group:{id}"),
        }
    }
}

fn load_config(path: &Path) -> anyhow::Result<Config> {
    let contents = match fs::read_to_string(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Err(UsageError(anyhow::anyhow!(
                "No assets config at {}. Create one as described in docs/assets.md, \
                 or pass --config.",
                path.display()
            ))
            .into())
        }
        Err(error) => return Err(error).with_context(|| format!("Cannot read {}", path.display())),
    };
    let file: ConfigFile = toml::from_str(&contents)
        .map_err(|error| UsageError(anyhow::anyhow!("{} is invalid: {error}", path.display())))?;
    let invalid = |message: String| UsageError(anyhow::anyhow!("{}: {message}", path.display()));

    let creator = match (file.creator.user_id, file.creator.group_id) {
        (Some(id), None) if id > 0 => Creator::User(id),
        (None, Some(id)) if id > 0 => Creator::Group(id),
        _ => {
            return Err(invalid(
                "[creator] needs exactly one of user_id or group_id, a positive number".to_owned(),
            )
            .into())
        }
    };
    if file.name_prefix.chars().count() >= MAX_DISPLAY_NAME_CHARS {
        return Err(invalid(format!(
            "name_prefix must be shorter than {MAX_DISPLAY_NAME_CHARS} characters, \
             since Roblox limits display names to {MAX_DISPLAY_NAME_CHARS}"
        ))
        .into());
    }
    if let Some(description) = &file.description {
        if description.chars().count() > MAX_DESCRIPTION_CHARS {
            return Err(invalid(format!(
                "description must be at most {MAX_DESCRIPTION_CHARS} characters"
            ))
            .into());
        }
    }
    let globs = |patterns: &[String]| -> anyhow::Result<Option<GlobSet>> {
        if patterns.is_empty() {
            return Ok(None);
        }
        let mut builder = GlobSetBuilder::new();
        for pattern in patterns {
            // `*` stays within one folder, like in .gitignore; `**` crosses folders.
            let glob = GlobBuilder::new(pattern)
                .literal_separator(true)
                .build()
                .map_err(|error| invalid(format!("invalid glob {pattern:?}: {error}")))?;
            builder.add(glob);
        }
        Ok(Some(builder.build()?))
    };

    let base = normalize(path.parent().unwrap_or(Path::new("")));
    let lock_name = format!(
        "{}.lock.json",
        path.file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or("assets")
    );
    Ok(Config {
        source: normalize(&base.join(&file.source)),
        output: normalize(&base.join(&file.output)),
        lock: base.join(lock_name),
        config: normalize(path),
        creator,
        name_prefix: file.name_prefix,
        description: file.description,
        include: globs(&file.include)?,
        exclude: globs(&file.exclude)?,
    })
}

/// Removes `.` and resolves `..` without touching the file system, so that
/// paths can be compared.
fn normalize(path: &Path) -> PathBuf {
    let mut normal = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                if !normal.pop() {
                    normal.push("..");
                }
            }
            other => normal.push(other),
        }
    }
    normal
}

#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
struct LockFile {
    version: u32,
    assets: BTreeMap<String, LockEntry>,
    /// Uploads that Roblox accepted but that did not finish in an earlier
    /// run, keyed by contents (see `pending_key`) rather than by path: a
    /// path's next upload must never replace the record of an unfinished
    /// upload whose contents have since moved to another path, or those
    /// contents would be sent again. Left out when empty, so lockfiles
    /// without any stay as they were.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pending: BTreeMap<String, PendingUpload>,
    /// Contents that Roblox rejected in moderation, keyed by BLAKE3 hash.
    /// Kept so that a rejected file is not sent again on every run, since
    /// each upload creates another rejected asset on the creator's account.
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    rejected: BTreeMap<String, RejectedUpload>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct RejectedUpload {
    /// The path the contents were uploaded from.
    path: String,
    asset_id: u64,
    asset_type: String,
    creator: String,
    /// RFC 3339 time Roblox reported the rejection.
    rejected: String,
}

/// The key of the pending upload of contents with `hash`, so that there is at
/// most one per asset type, creator and contents.
fn pending_key(asset_type: &str, creator: &str, hash: &str) -> String {
    format!("{asset_type}/{creator}/{hash}")
}

/// An upload that Roblox accepted as an operation, recorded so that the next
/// run polls the operation instead of creating a second asset.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct PendingUpload {
    /// The path the file was sent from, for messages. Empty only while
    /// reading a lockfile from before `pending` was keyed by contents, whose
    /// keys were these paths.
    #[serde(default)]
    path: String,
    /// BLAKE3 hash of the file that was sent.
    hash: String,
    asset_type: String,
    creator: String,
    /// The Assets API operation, such as `operations/abc`.
    operation: String,
    /// RFC 3339 time the file was sent.
    started: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct LockEntry {
    /// BLAKE3 hash of the file's contents, in hex.
    hash: String,
    asset_id: u64,
    /// `Image`, `Audio` or `Model`.
    asset_type: String,
    /// `user:<id>` or `group:<id>`. Ids are only reused for the same creator.
    creator: String,
    /// As Roblox reported it when the upload finished.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    moderation_state: Option<String>,
    /// RFC 3339 time of the upload.
    uploaded: String,
}

fn load_lock(path: &Path) -> anyhow::Result<LockFile> {
    let contents = match fs::read_to_string(path) {
        Ok(contents) => contents,
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            return Ok(LockFile {
                version: LOCK_VERSION,
                ..LockFile::default()
            })
        }
        Err(error) => return Err(error).with_context(|| format!("Cannot read {}", path.display())),
    };
    let lock: LockFile = serde_json::from_str(&contents).with_context(|| {
        format!(
            "{} is not a valid assets lockfile. If a merge conflict damaged it, \
             resolve the conflict by keeping both sides' entries.",
            path.display()
        )
    })?;
    if lock.version > LOCK_VERSION {
        bail!(
            "{} has version {}, which a newer Rojo wrote; this Rojo only reads version \
             {LOCK_VERSION}. Upgrade Rojo to sync with it.",
            path.display(),
            lock.version
        );
    }
    if lock.version != LOCK_VERSION {
        bail!(
            "{} has version {}, but this Rojo only reads version {LOCK_VERSION}",
            path.display(),
            lock.version
        );
    }
    Ok(rekey_pending(lock))
}

/// Keys every pending upload by its contents. Earlier builds of this format
/// keyed them by path and had no `path` field, so such a key moves into
/// `path`. Two such entries with the same contents are both waiting on an
/// asset of those contents, so keeping either one is enough.
///
/// This shape was never released, so reading it needs no version bump.
fn rekey_pending(mut lock: LockFile) -> LockFile {
    for (key, mut pending) in std::mem::take(&mut lock.pending) {
        if pending.path.is_empty() {
            pending.path = key;
        }
        lock.pending
            .entry(pending_key(
                &pending.asset_type,
                &pending.creator,
                &pending.hash,
            ))
            .or_insert(pending);
    }
    lock
}

fn render_lock(lock: &LockFile) -> String {
    let mut text = serde_json::to_string_pretty(lock).expect("lockfiles always serialize");
    text.push('\n');
    text
}

/// Writes the file through a temporary file in the same folder and a rename,
/// so a crash leaves either the old or the new contents.
fn write_atomic(path: &Path, contents: &str) -> anyhow::Result<()> {
    let dir = path.parent().unwrap_or(Path::new("."));
    fs::create_dir_all(dir).with_context(|| format!("Cannot create {}", dir.display()))?;
    let mut file = tempfile::NamedTempFile::new_in(dir)
        .with_context(|| format!("Cannot create a temporary file in {}", dir.display()))?;
    file.write_all(contents.as_bytes())?;
    file.as_file().sync_all()?;
    file.persist(path)
        .map_err(|error| error.error)
        .with_context(|| format!("Cannot write {}", path.display()))?;
    // On Unix the rename itself is only durable once the folder is synced.
    // Failing to sync is not worth failing the write over.
    #[cfg(unix)]
    if let Ok(dir) = fs::File::open(dir) {
        let _ = dir.sync_all();
    }
    Ok(())
}

/// Writes the file only when its contents differ. Returns whether it wrote.
fn write_if_changed(path: &Path, contents: &str) -> anyhow::Result<bool> {
    if fs::read_to_string(path).ok().as_deref() == Some(contents) {
        return Ok(false);
    }
    write_atomic(path, contents)?;
    Ok(true)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Image,
    Audio,
    Model,
}

impl Kind {
    fn name(self) -> &'static str {
        match self {
            Kind::Image => "Image",
            Kind::Audio => "Audio",
            Kind::Model => "Model",
        }
    }

    fn asset_type(self) -> AssetType {
        match self {
            // Image ids work directly in `rbxassetid://`; Decal ids do not.
            Kind::Image => AssetType::Image,
            Kind::Audio => AssetType::Audio,
            Kind::Model => AssetType::Model,
        }
    }
}

/// Picks the asset type and content type from a lowercase extension, or says
/// why the file cannot be uploaded.
fn classify(extension: &str) -> Result<(Kind, &'static str), &'static str> {
    Ok(match extension {
        "png" => (Kind::Image, "image/png"),
        "jpg" | "jpeg" => (Kind::Image, "image/jpeg"),
        "bmp" => (Kind::Image, "image/bmp"),
        "tga" => (Kind::Image, "image/tga"),
        "mp3" => (Kind::Audio, "audio/mpeg"),
        "ogg" => (Kind::Audio, "audio/ogg"),
        "flac" => (Kind::Audio, "audio/flac"),
        "wav" => (Kind::Audio, "audio/wav"),
        "fbx" => (Kind::Model, "model/fbx"),
        "gltf" => (Kind::Model, "model/gltf+json"),
        "glb" => (Kind::Model, "model/gltf-binary"),
        "obj" => {
            return Err("Open Cloud does not accept OBJ models; export it as FBX, glTF or GLB")
        }
        _ => {
            return Err(
                "not a format Open Cloud accepts (png, jpg, jpeg, bmp, tga, mp3, ogg, flac, \
                 wav, fbx, gltf, glb); add it to `exclude` to silence this",
            )
        }
    })
}

/// One file to sync.
#[derive(Debug, Clone)]
struct Source {
    /// Path relative to the source folder, with `/` separators.
    rel: String,
    path: PathBuf,
    kind: Kind,
    content_type: &'static str,
    hash: String,
    size: u64,
}

struct Scan {
    sources: Vec<Source>,
    warnings: Vec<String>,
}

/// Finds, hashes and checks every file. Fails with every problem found when
/// any file cannot be uploaded or two files would get the same module key.
fn scan(config: &Config) -> anyhow::Result<Scan> {
    if !config.source.is_dir() {
        return Err(UsageError(anyhow::anyhow!(
            "The asset folder {} does not exist",
            config.source.display()
        ))
        .into());
    }
    let mut files = Vec::new();
    walk(&config.source, "", &mut files)?;

    let ignored = [&config.output, &config.lock, &config.config];
    let mut sources = Vec::new();
    let mut warnings = Vec::new();
    let mut errors = Vec::new();
    for (rel, path) in files {
        let rel_path = Path::new(&rel);
        if ignored.iter().any(|ignored| **ignored == path)
            || config
                .include
                .as_ref()
                .is_some_and(|include| !include.is_match(rel_path))
            || config
                .exclude
                .as_ref()
                .is_some_and(|exclude| exclude.is_match(rel_path))
        {
            continue;
        }
        let extension = rel_path
            .extension()
            .and_then(|extension| extension.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        let (kind, content_type) = match classify(&extension) {
            Ok(classified) => classified,
            Err(reason) => {
                warnings.push(format!("skipped {rel}: {reason}"));
                continue;
            }
        };
        // Checking the size first keeps a stray multi-gigabyte file from
        // being read into memory only to be refused.
        let size = fs::metadata(&path)
            .with_context(|| format!("Cannot read {}", path.display()))?
            .len();
        if let Err(problem) = check_size(size) {
            errors.push(format!("{rel}: {problem}"));
            continue;
        }
        let bytes = fs::read(&path).with_context(|| format!("Cannot read {}", path.display()))?;
        if let Err(problem) = check_file(&extension, &bytes) {
            errors.push(format!("{rel}: {problem}"));
            continue;
        }
        sources.push(Source {
            hash: blake3::hash(&bytes).to_hex().to_string(),
            size: bytes.len() as u64,
            rel,
            path,
            kind,
            content_type,
        });
    }

    if let Err(collisions) = build_tree(sources.iter().map(|source| (source.rel.as_str(), 0))) {
        errors.extend(collisions);
    }
    if !errors.is_empty() {
        bail!(
            "Cannot sync assets; nothing was uploaded:\n  {}",
            errors.join("\n  ")
        );
    }
    Ok(Scan { sources, warnings })
}

/// Lists files under `dir` in a stable order. Hidden files and folders, such
/// as `.DS_Store`, are skipped, and symbolic links to folders are not
/// followed so that a link cannot loop.
fn walk(dir: &Path, prefix: &str, files: &mut Vec<(String, PathBuf)>) -> anyhow::Result<()> {
    let mut entries = fs::read_dir(dir)
        .with_context(|| format!("Cannot list {}", dir.display()))?
        .collect::<Result<Vec<_>, _>>()
        .with_context(|| format!("Cannot list {}", dir.display()))?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            bail!(
                "{} has a name that is not valid Unicode",
                entry.path().display()
            );
        };
        if name.starts_with('.') {
            continue;
        }
        let rel = format!("{prefix}{name}");
        let path = entry.path();
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            walk(&path, &format!("{rel}/"), files)?;
        } else if file_type.is_file() || (file_type.is_symlink() && path.is_file()) {
            files.push((rel, path));
        }
    }
    Ok(())
}

/// Checks a file against Open Cloud's limits and its format's signature, so
/// that problems show up before anything is uploaded.
fn check_file(extension: &str, bytes: &[u8]) -> Result<(), String> {
    // Checked again since the file may have changed after its metadata was
    // read.
    check_size(bytes.len() as u64)?;
    let not_valid = |format: &str| Err(format!("the file is not a valid {format} file"));
    match extension {
        "png" | "jpg" | "jpeg" | "bmp" | "tga" => {
            let Some((width, height)) = image_size(extension, bytes) else {
                return not_valid(&extension.to_ascii_uppercase());
            };
            if width >= MAX_IMAGE_SIDE || height >= MAX_IMAGE_SIDE {
                return Err(format!(
                    "the image is {width}x{height}; Roblox accepts images smaller than \
                     {MAX_IMAGE_SIDE}x{MAX_IMAGE_SIDE}"
                ));
            }
        }
        "mp3" => {
            let frame = bytes.len() >= 2 && bytes[0] == 0xFF && bytes[1] & 0xE0 == 0xE0;
            if !(bytes.starts_with(b"ID3") || frame) {
                return not_valid("MP3");
            }
        }
        "ogg" if !bytes.starts_with(b"OggS") => return not_valid("Ogg"),
        "flac" if !bytes.starts_with(b"fLaC") => return not_valid("FLAC"),
        "wav" if !(bytes.starts_with(b"RIFF") && bytes.get(8..12) == Some(b"WAVE")) => {
            return not_valid("WAV")
        }
        "glb" if !bytes.starts_with(b"glTF") => return not_valid("GLB"),
        "gltf" => check_gltf(bytes)?,
        _ => {}
    }
    Ok(())
}

fn check_size(size: u64) -> Result<(), String> {
    if size == 0 {
        return Err("the file is empty".to_owned());
    }
    if size > MAX_FILE_BYTES {
        // Exact byte counts, since a rounded size just over the limit reads
        // as if it were within it.
        return Err(format!(
            "the file is {size} bytes; Open Cloud accepts files up to {MAX_FILE_BYTES} bytes \
             (20 MB)"
        ));
    }
    Ok(())
}

/// Open Cloud receives a single file, so a glTF that points at separate
/// buffer or texture files would arrive incomplete.
fn check_gltf(bytes: &[u8]) -> Result<(), String> {
    let gltf: serde_json::Value =
        serde_json::from_slice(bytes).map_err(|_| "the file is not valid glTF JSON".to_owned())?;
    for list in ["buffers", "images"] {
        for item in gltf[list].as_array().into_iter().flatten() {
            if let Some(uri) = item["uri"].as_str() {
                if !uri.starts_with("data:") {
                    return Err(format!(
                        "it refers to the separate file {uri:?}, which Open Cloud cannot \
                         receive; export it as GLB or with embedded resources"
                    ));
                }
            }
        }
    }
    Ok(())
}

/// Reads an image's width and height from its header.
fn image_size(extension: &str, bytes: &[u8]) -> Option<(u32, u32)> {
    let be32 = |at: usize| Some(u32::from_be_bytes(bytes.get(at..at + 4)?.try_into().ok()?));
    let le32 = |at: usize| Some(i32::from_le_bytes(bytes.get(at..at + 4)?.try_into().ok()?));
    let le16 = |at: usize| Some(u16::from_le_bytes(bytes.get(at..at + 2)?.try_into().ok()?));
    let be16 = |at: usize| Some(u16::from_be_bytes(bytes.get(at..at + 2)?.try_into().ok()?));
    match extension {
        "png" => {
            if !bytes.starts_with(b"\x89PNG\r\n\x1a\n") || bytes.get(12..16) != Some(b"IHDR") {
                return None;
            }
            Some((be32(16)?, be32(20)?))
        }
        "bmp" => {
            if !bytes.starts_with(b"BM") {
                return None;
            }
            // Height is negative for top-down bitmaps.
            Some((le32(18)?.unsigned_abs(), le32(22)?.unsigned_abs()))
        }
        // TGA has no signature; its size is at a fixed offset.
        "tga" => Some((u32::from(le16(12)?), u32::from(le16(14)?))),
        _ => {
            // JPEG: walk the segments until a start-of-frame marker.
            if !bytes.starts_with(&[0xFF, 0xD8]) {
                return None;
            }
            let mut at = 2;
            loop {
                if *bytes.get(at)? != 0xFF {
                    return None;
                }
                let marker = *bytes.get(at + 1)?;
                match marker {
                    // Fill bytes, and markers without a length.
                    0xFF => at += 1,
                    0x01 | 0xD0..=0xD7 => at += 2,
                    0xC0..=0xCF if !matches!(marker, 0xC4 | 0xC8 | 0xCC) => {
                        return Some((u32::from(be16(at + 7)?), u32::from(be16(at + 5)?)));
                    }
                    0xD9 | 0xDA => return None,
                    _ => at += 2 + usize::from(be16(at + 2)?),
                }
            }
        }
    }
}

/// A module table: folders become nested tables, files become ids.
enum Node<'a> {
    Folder {
        path: String,
        children: BTreeMap<String, Node<'a>>,
    },
    Asset {
        rel: &'a str,
        id: u64,
    },
}

/// Builds the module's tables, keyed by folder names and file names without
/// their extension. Fails with one message per pair of paths that would get
/// the same key.
fn build_tree<'a>(
    assets: impl IntoIterator<Item = (&'a str, u64)>,
) -> Result<BTreeMap<String, Node<'a>>, Vec<String>> {
    let mut root = BTreeMap::new();
    let mut errors = Vec::new();
    'assets: for (rel, id) in assets {
        let mut parts: Vec<&str> = rel.split('/').collect();
        let file = parts.pop().unwrap_or(rel);
        let key = match file.rsplit_once('.') {
            Some((stem, _)) if !stem.is_empty() => stem,
            _ => file,
        };
        let mut table = &mut root;
        let mut folder = String::new();
        for part in parts {
            folder.push_str(part);
            let node = table
                .entry(part.to_owned())
                .or_insert_with(|| Node::Folder {
                    path: folder.clone(),
                    children: BTreeMap::new(),
                });
            folder.push('/');
            match node {
                Node::Folder { children, .. } => table = children,
                Node::Asset { rel: other, .. } => {
                    errors.push(format!(
                        "{other} and the folder {} would both be named {part:?} in the module; \
                         rename one of them",
                        folder.trim_end_matches('/')
                    ));
                    continue 'assets;
                }
            }
        }
        match table.get(key) {
            None => {
                table.insert(key.to_owned(), Node::Asset { rel, id });
            }
            Some(Node::Asset { rel: other, .. }) => errors.push(format!(
                "{other} and {rel} would both be named {key:?} in the module; rename one of them"
            )),
            Some(Node::Folder { path, .. }) => errors.push(format!(
                "{rel} and the folder {path} would both be named {key:?} in the module; \
                 rename one of them"
            )),
        }
    }
    if errors.is_empty() {
        Ok(root)
    } else {
        Err(errors)
    }
}

fn render_module(tree: &BTreeMap<String, Node<'_>>) -> String {
    fn table(output: &mut String, children: &BTreeMap<String, Node<'_>>, depth: usize) {
        if children.is_empty() {
            output.push_str("{}");
            return;
        }
        output.push_str("{\n");
        for (key, node) in children {
            output.push_str(&"\t".repeat(depth + 1));
            write_key(output, key);
            output.push_str(" = ");
            match node {
                Node::Folder { children, .. } => table(output, children, depth + 1),
                Node::Asset { id, .. } => write!(output, "\"rbxassetid://{id}\"").unwrap(),
            }
            output.push_str(",\n");
        }
        output.push_str(&"\t".repeat(depth));
        output.push('}');
    }
    let mut output = format!("{MODULE_HEADER}\nreturn ");
    table(&mut output, tree, 0);
    output.push('\n');
    output
}

fn write_key(output: &mut String, key: &str) {
    if is_valid_ident(key) {
        output.push_str(key);
        return;
    }
    output.push_str("[\"");
    for c in key.chars() {
        match c {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            // Three digits, so a digit that follows is not read as part of
            // the escape.
            c if c.is_ascii_control() => write!(output, "\\{:03}", c as u32).unwrap(),
            c => output.push(c),
        }
    }
    output.push_str("\"]");
}

fn is_valid_ident(value: &str) -> bool {
    // Luau's contextual keywords (`continue`, `type`, `export`) are valid
    // field names, so only the reserved words are listed.
    const KEYWORDS: &[&str] = &[
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
        "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
    ];
    let mut chars = value.chars();
    matches!(chars.next(), Some(first) if first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !KEYWORDS.contains(&value)
}

#[derive(Debug, Clone, PartialEq)]
enum Action {
    Unchanged,
    /// Upload because the path is new, or because its contents changed.
    Upload {
        changed: bool,
        /// An earlier run's unfinished upload of the same contents, which is
        /// polled instead of sending the file again.
        resume: Option<Resume>,
    },
    /// Reuse an id from the lockfile for the same contents at another path.
    Reuse {
        from: String,
        entry: LockEntry,
    },
    /// Reuse the id of an identical file uploaded earlier in this run.
    SameAs {
        from: String,
    },
    /// Not uploaded, because Roblox rejected these exact contents in
    /// moderation before and `--retry-rejected` was not given.
    Rejected(RejectedUpload),
}

#[derive(Debug, Clone, PartialEq)]
struct Resume {
    /// The key of the entry in the lockfile's `pending`.
    key: String,
    operation: String,
}

struct Plan {
    items: Vec<(Source, Action)>,
    /// Lockfile paths whose files are gone.
    removed: Vec<String>,
    /// Pending uploads that no file resumes, because the file changed, is
    /// gone or got an id another way. Dropped after a successful sync.
    stale_pending: Vec<String>,
}

impl Plan {
    fn uploads(&self) -> usize {
        self.items
            .iter()
            .filter(|(_, action)| matches!(action, Action::Upload { .. }))
            .count()
    }

    fn rejected(&self) -> Vec<(&Source, &RejectedUpload)> {
        self.items
            .iter()
            .filter_map(|(source, action)| match action {
                Action::Rejected(rejected) => Some((source, rejected)),
                _ => None,
            })
            .collect()
    }
}

fn plan(sources: &[Source], lock: &LockFile, config: &Config, retry_rejected: bool) -> Plan {
    let creator = config.creator_key();
    let reusable = |entry: &LockEntry, source: &Source| {
        entry.creator == creator && entry.asset_type == source.kind.name()
    };

    // The first path in sorted order wins when several share contents.
    let mut by_hash: HashMap<&str, (&str, &LockEntry)> = HashMap::new();
    for (rel, entry) in &lock.assets {
        if entry.creator == creator {
            by_hash.entry(&entry.hash).or_insert((rel, entry));
        }
    }
    let mut uploading: HashMap<&str, &str> = HashMap::new();
    let mut items = Vec::new();
    for source in sources {
        let existing = lock.assets.get(&source.rel);
        let action = match existing {
            Some(entry) if entry.hash == source.hash && reusable(entry, source) => {
                Action::Unchanged
            }
            _ => match by_hash.get(source.hash.as_str()) {
                Some((from, entry)) if reusable(entry, source) => Action::Reuse {
                    from: (*from).to_owned(),
                    entry: (*entry).clone(),
                },
                _ => match uploading.get(source.hash.as_str()) {
                    Some(from) => Action::SameAs {
                        from: (*from).to_owned(),
                    },
                    None => {
                        // Found by contents, so it follows a rename.
                        let resume = lock
                            .pending
                            .get_key_value(&pending_key(source.kind.name(), &creator, &source.hash))
                            .map(|(key, pending)| Resume {
                                key: key.clone(),
                                operation: pending.operation.clone(),
                            });
                        // Checking on a pending upload sends nothing, so it
                        // goes ahead even for rejected contents.
                        let rejected = lock.rejected.get(&source.hash).filter(|rejected| {
                            !retry_rejected
                                && resume.is_none()
                                && rejected.creator == creator
                                && rejected.asset_type == source.kind.name()
                        });
                        match rejected {
                            Some(rejected) => Action::Rejected(rejected.clone()),
                            None => {
                                uploading.insert(&source.hash, &source.rel);
                                Action::Upload {
                                    changed: existing.is_some(),
                                    resume,
                                }
                            }
                        }
                    }
                },
            },
        };
        items.push((source.clone(), action));
    }
    let present: BTreeSet<&str> = sources.iter().map(|source| source.rel.as_str()).collect();
    let removed = lock
        .assets
        .keys()
        .filter(|rel| !present.contains(rel.as_str()))
        .cloned()
        .collect();
    let resumed: BTreeSet<&str> = items
        .iter()
        .filter_map(|(_, action)| match action {
            Action::Upload {
                resume: Some(resume),
                ..
            } => Some(resume.key.as_str()),
            _ => None,
        })
        .collect();
    let stale_pending = lock
        .pending
        .keys()
        .filter(|key| !resumed.contains(key.as_str()))
        .cloned()
        .collect();
    Plan {
        items,
        removed,
        stale_pending,
    }
}

fn describe_plan(
    plan: &Plan,
    lock: &LockFile,
    dry_run: bool,
    out: &mut dyn Write,
) -> io::Result<()> {
    let upload_verb = if dry_run { "would upload" } else { "to upload" };
    for (source, action) in &plan.items {
        match action {
            Action::Unchanged => {}
            Action::Upload {
                resume: Some(resume),
                ..
            } => writeln!(
                out,
                "  resume    {} ({}, {}) {} {}, which an earlier sync started",
                source.rel,
                source.kind.name(),
                format_size(source.size),
                if dry_run {
                    "would check on"
                } else {
                    "to check on"
                },
                resume.operation
            )?,
            Action::Upload { changed, .. } => writeln!(
                out,
                "  {:<9} {} ({}, {}) {upload_verb}",
                if *changed { "changed" } else { "new" },
                source.rel,
                source.kind.name(),
                format_size(source.size)
            )?,
            Action::Reuse { from, entry } if plan.removed.contains(from) => writeln!(
                out,
                "  renamed   {from} -> {} (keeps asset {})",
                source.rel, entry.asset_id
            )?,
            Action::Reuse { from, entry } => writeln!(
                out,
                "  copy      {} (same contents as {from}, reuses asset {})",
                source.rel, entry.asset_id
            )?,
            Action::SameAs { from } => writeln!(
                out,
                "  copy      {} (same contents as {from}, reuses its upload)",
                source.rel
            )?,
            Action::Rejected(rejected) => writeln!(
                out,
                "  rejected  {} ({}) was rejected in moderation as asset {} on {} and is not \
                 uploaded again; replace the file or pass --retry-rejected",
                source.rel,
                source.kind.name(),
                rejected.asset_id,
                rejected.rejected
            )?,
        }
    }
    let renamed: BTreeSet<&str> = plan
        .items
        .iter()
        .filter_map(|(_, action)| match action {
            Action::Reuse { from, .. } => Some(from.as_str()),
            _ => None,
        })
        .collect();
    for rel in &plan.removed {
        if !renamed.contains(rel.as_str()) {
            writeln!(
                out,
                "  missing   {rel} (asset {} stays on Roblox)",
                lock.assets[rel].asset_id
            )?;
        }
    }
    for key in &plan.stale_pending {
        let pending = &lock.pending[key];
        writeln!(
            out,
            "  stale     unfinished upload of {} ({}) is no longer needed and will be \
             forgotten; if Roblox created an asset for it, that asset stays unused",
            pending.path, pending.operation
        )?;
    }
    Ok(())
}

fn format_size(bytes: u64) -> String {
    if bytes < 1024 {
        format!("{bytes} B")
    } else if bytes < 1024 * 1024 {
        format!("{:.1} KB", bytes as f64 / 1024.0)
    } else {
        format!("{:.1} MB", bytes as f64 / (1024.0 * 1024.0))
    }
}

/// The lockfile after applying every change that needs no upload: reused ids
/// and removals.
fn offline_lock(plan: &Plan, lock: &LockFile) -> LockFile {
    let mut next = lock.clone();
    for (source, action) in &plan.items {
        if let Action::Reuse { entry, .. } = action {
            next.assets.insert(source.rel.clone(), entry.clone());
        }
    }
    for rel in &plan.removed {
        next.assets.remove(rel);
    }
    next
}

fn module_for(sources: &[Source], lock: &LockFile) -> Option<String> {
    let ids: Option<Vec<(&str, u64)>> = sources
        .iter()
        .map(|source| {
            let entry = lock.assets.get(&source.rel)?;
            Some((source.rel.as_str(), entry.asset_id))
        })
        .collect();
    let tree = build_tree(ids?).expect("collisions were checked while scanning");
    Some(render_module(&tree))
}

fn display_path(config: &Config, path: &Path) -> String {
    let base = config.config.parent().unwrap_or(Path::new(""));
    path.strip_prefix(base)
        .unwrap_or(path)
        .display()
        .to_string()
        .replace('\\', "/")
}

/// Reports what `sync` would do, without network access.
fn status(config_path: &Path, out: &mut dyn Write) -> anyhow::Result<()> {
    let config = load_config(config_path)?;
    let scan = scan(&config)?;
    for warning in &scan.warnings {
        writeln!(out, "warning: {warning}")?;
    }
    let lock = load_lock(&config.lock)?;
    let plan = plan(&scan.sources, &lock, &config, false);
    describe_plan(&plan, &lock, false, out)?;
    for (rel, entry) in &lock.assets {
        if let Some(state) = entry
            .moderation_state
            .as_deref()
            .filter(|state| *state != "Approved")
        {
            writeln!(
                out,
                "  moderation {rel} (asset {} was {state} when uploaded)",
                entry.asset_id
            )?;
        }
    }

    let unchanged = plan
        .items
        .iter()
        .filter(|(_, action)| *action == Action::Unchanged)
        .count();
    let uploads = plan.uploads();
    let rejected = plan.rejected().len();
    writeln!(
        out,
        "{} file(s): {unchanged} unchanged, {uploads} to upload, {} reusing an id, {rejected} \
         rejected, {} removed.",
        plan.items.len(),
        plan.items.len() - unchanged - uploads - rejected,
        plan.removed.len()
    )?;
    let output = display_path(&config, &config.output);
    let module = module_for(&scan.sources, &offline_lock(&plan, &lock));
    let current = fs::read_to_string(&config.output).ok();
    match module {
        _ if rejected > 0 => writeln!(
            out,
            "Replace the rejected file(s), or pass --retry-rejected to `rojo assets sync`, to \
             update {output}."
        )?,
        _ if uploads > 0 => writeln!(out, "Run `rojo assets sync` to upload and update {output}.")?,
        Some(module) if current.as_deref() == Some(module.as_str()) => {
            writeln!(out, "{output} is up to date.")?
        }
        _ => writeln!(out, "Run `rojo assets sync` to update {output}.")?,
    }
    Ok(())
}

/// What a sync did.
#[derive(Debug, Default, PartialEq)]
struct SyncReport {
    uploaded: Vec<(String, u64)>,
    module_written: bool,
}

#[derive(Debug, Clone, Copy, Default)]
struct SyncOptions {
    dry_run: bool,
    retry_rejected: bool,
}

/// Held for the whole of a sync that may write, so that two syncs of one
/// config cannot both read the lockfile and upload the same new files. The
/// file is removed when the guard drops, including on errors and panics; a
/// killed process leaves it behind, and so does Ctrl+C, since Rojo installs
/// no handler and the process ends without unwinding. The error for a
/// leftover file explains how to remove it.
struct SyncLock {
    path: PathBuf,
}

impl SyncLock {
    fn acquire(config: &Config) -> anyhow::Result<SyncLock> {
        let mut name = config.lock.file_name().unwrap_or_default().to_owned();
        name.push(".lock");
        let path = config.lock.with_file_name(name);
        match fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
        {
            Ok(mut file) => {
                let guard = SyncLock { path };
                // The contents only help someone deciding whether the lock is
                // stale, so failing to write them is not an error.
                let _ = write!(
                    file,
                    "pid {}\nstarted {}\n",
                    std::process::id(),
                    humantime::format_rfc3339_seconds(SystemTime::now())
                );
                Ok(guard)
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {
                let holder = fs::read_to_string(&path).unwrap_or_default();
                let holder = holder.split_whitespace().collect::<Vec<_>>().join(" ");
                let display = display_path(config, &path);
                bail!(
                    "Another `rojo assets sync` is running for this config: {display} exists{}. \
                     Wait for it to finish. If no sync is running, for example because one was \
                     killed, delete {display} and run sync again.",
                    if holder.is_empty() {
                        String::new()
                    } else {
                        format!(" ({holder})")
                    }
                )
            }
            Err(error) => Err(error).with_context(|| format!("Cannot create {}", path.display())),
        }
    }
}

impl Drop for SyncLock {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.path);
    }
}

fn sync(
    config_path: &Path,
    options: SyncOptions,
    connect: impl FnOnce() -> anyhow::Result<OpenCloud>,
    out: &mut dyn Write,
) -> anyhow::Result<SyncReport> {
    let SyncOptions {
        dry_run,
        retry_rejected,
    } = options;
    let config = load_config(config_path)?;
    // Taken before the lockfile is read, since a second sync that read it
    // while this one uploads would upload the same files. A dry run writes
    // nothing, so it does not need the lock.
    let _sync_lock = if dry_run {
        None
    } else {
        Some(SyncLock::acquire(&config)?)
    };
    let scan = scan(&config)?;
    for warning in &scan.warnings {
        writeln!(out, "warning: {warning}")?;
    }
    let old_lock = load_lock(&config.lock)?;
    let plan = plan(&scan.sources, &old_lock, &config, retry_rejected);
    describe_plan(&plan, &old_lock, dry_run, out)?;
    let total = plan.uploads();
    let output = display_path(&config, &config.output);
    let rejected = plan.rejected();
    if dry_run {
        writeln!(
            out,
            "Dry run: {total} file(s) would be uploaded. Nothing was uploaded or written."
        )?;
        if !rejected.is_empty() {
            writeln!(
                out,
                "A sync would stop before uploading: {} file(s) were rejected in moderation \
                 before.",
                rejected.len()
            )?;
        }
        return Ok(SyncReport::default());
    }
    // Like a file that fails the size checks, this stops the run before
    // anything is uploaded, since the module needs an id for every file.
    if !rejected.is_empty() {
        let list: Vec<String> = rejected
            .iter()
            .map(|(source, rejected)| {
                format!(
                    "{} (asset {}, rejected on {})",
                    source.rel, rejected.asset_id, rejected.rejected
                )
            })
            .collect();
        bail!(
            "Roblox rejected the contents of {} in moderation in an earlier sync, so they are not \
             uploaded again: each upload would create another rejected asset. Replace or \
             exclude the file(s), or pass --retry-rejected to upload them again.",
            list.join(", ")
        );
    }

    let mut report = SyncReport::default();
    let mut lock = old_lock.clone();
    // Recording reused ids first keeps them when an upload below replaces the
    // entry they were copied from and the run is then interrupted.
    for (source, action) in &plan.items {
        if let Action::Reuse { entry, .. } = action {
            lock.assets.insert(source.rel.clone(), entry.clone());
        }
    }
    if lock != old_lock {
        write_atomic(&config.lock, &render_lock(&lock))?;
    }

    if total > 0 {
        let client = connect()?;
        let creator = config.creator_key();
        let uploads = plan
            .items
            .iter()
            .filter_map(|(source, action)| match action {
                Action::Upload { resume, .. } => Some((source, resume)),
                _ => None,
            });
        for (index, (source, resume)) in uploads.enumerate() {
            match resume {
                Some(resume) => write!(
                    out,
                    "[{}/{total}] Checking on the earlier upload of {} ({})... ",
                    index + 1,
                    source.rel,
                    resume.operation
                )?,
                None => write!(
                    out,
                    "[{}/{total}] Uploading {} ({}, {})... ",
                    index + 1,
                    source.rel,
                    source.kind.name(),
                    format_size(source.size)
                )?,
            }
            out.flush()?;
            let entry = upload(
                &client,
                &config,
                source,
                resume.as_ref(),
                &creator,
                &mut lock,
            )
            .map_err(|error| {
                let saved = report.uploaded.len();
                error.context(format!(
                    "{saved} earlier upload(s) in this run were saved to {}",
                    display_path(&config, &config.lock)
                ))
            })?;
            match entry.moderation_state.as_deref() {
                Some("Approved") | None => writeln!(out, "asset {}", entry.asset_id)?,
                Some(state) => {
                    writeln!(out, "asset {} ({state})", entry.asset_id)?;
                    writeln!(
                        out,
                        "warning: {} is {state} in moderation; its id is recorded but may not \
                         load until Roblox approves it",
                        source.rel
                    )?;
                }
            }
            report.uploaded.push((source.rel.clone(), entry.asset_id));
            // Contents retried with --retry-rejected that passed this time.
            lock.rejected.remove(&source.hash);
            lock.assets.insert(source.rel.clone(), entry);
            write_atomic(&config.lock, &render_lock(&lock))?;
        }
    }

    for (source, action) in &plan.items {
        if let Action::SameAs { from } = action {
            let entry = lock.assets[from].clone();
            lock.assets.insert(source.rel.clone(), entry);
        }
    }
    for rel in &plan.removed {
        lock.assets.remove(rel);
    }
    for key in &plan.stale_pending {
        lock.pending.remove(key);
    }
    write_if_changed(&config.lock, &render_lock(&lock))?;

    let module = module_for(&scan.sources, &lock).expect("every file has a lockfile entry");
    report.module_written = write_if_changed(&config.output, &module)?;
    writeln!(
        out,
        "{} uploaded, {} file(s) in total. {output} {}.",
        report.uploaded.len(),
        plan.items.len(),
        if report.module_written {
            "was updated"
        } else {
            "is up to date"
        }
    )?;
    Ok(report)
}

/// Uploads one file, or finishes the earlier upload `resume` names, and
/// returns its lockfile entry. Fails when Roblox rejects it in moderation,
/// since its id would not load.
///
/// Once Roblox has accepted the file, the operation is written to `lock`'s
/// `pending` (and to disk) before polling, so an upload that cannot be
/// followed to the end is resumed by the next run rather than repeated. On
/// success the pending entry is removed from `lock`, and the caller writes
/// it together with the new asset entry.
fn upload(
    client: &OpenCloud,
    config: &Config,
    source: &Source,
    resume: Option<&Resume>,
    creator: &str,
    lock: &mut LockFile,
) -> anyhow::Result<LockEntry> {
    let (key, operation, result) = match resume {
        Some(resume) => (
            resume.key.clone(),
            resume.operation.clone(),
            client.resume_asset_upload(&resume.operation),
        ),
        None => {
            let started = start_upload(client, config, source)?;
            let operation = started.operation.clone();
            let key = pending_key(source.kind.name(), creator, &source.hash);
            // `plan` resumes a pending upload of these contents rather than
            // sending them again, so this never replaces another operation.
            debug_assert!(!lock.pending.contains_key(&key));
            lock.pending.insert(
                key.clone(),
                PendingUpload {
                    path: source.rel.clone(),
                    hash: source.hash.clone(),
                    asset_type: source.kind.name().to_owned(),
                    creator: creator.to_owned(),
                    operation: operation.clone(),
                    started: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
                },
            );
            write_atomic(&config.lock, &render_lock(lock)).with_context(|| {
                format!(
                    "Roblox accepted the upload of {} as {operation}, but it could not be \
                     recorded; check the creator's assets before running sync again, since a \
                     rerun uploads the file again",
                    source.rel
                )
            })?;
            (key, operation, client.finish_asset_upload(started))
        }
    };
    let uploaded = match result {
        Ok(uploaded) => {
            lock.pending.remove(&key);
            uploaded
        }
        // Roblox finished the operation and created nothing, so the next
        // run should send the file again.
        Err(error @ OpenCloudError::Failed(_)) => {
            lock.pending.remove(&key);
            write_atomic(&config.lock, &render_lock(lock))?;
            bail!("Could not upload {}: {error}.", source.rel);
        }
        Err(error) => bail!(
            "Could not finish uploading {}: {error}. Roblox accepted the file as {operation}, \
             which is recorded in {}; the next `rojo assets sync` checks on it instead of \
             uploading the file again. If that keeps failing, check the creator's assets, \
             then remove the entry {key} under \"pending\" in the lockfile to upload it \
             again.",
            source.rel,
            display_path(config, &config.lock)
        ),
    };
    if uploaded.moderation_state.as_deref() == Some("Rejected") {
        // Recorded so that later runs do not send the same contents again.
        lock.rejected.insert(
            source.hash.clone(),
            RejectedUpload {
                path: source.rel.clone(),
                asset_id: uploaded.asset_id,
                asset_type: source.kind.name().to_owned(),
                creator: creator.to_owned(),
                rejected: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
            },
        );
        write_atomic(&config.lock, &render_lock(lock))?;
        bail!(
            "Roblox rejected {} in moderation (asset {}). The rejection is recorded in {}, so \
             later syncs do not upload these contents again; replace the file and sync again, \
             or pass --retry-rejected.",
            source.rel,
            uploaded.asset_id,
            display_path(config, &config.lock)
        );
    }
    Ok(LockEntry {
        hash: source.hash.clone(),
        asset_id: uploaded.asset_id,
        asset_type: source.kind.name().to_owned(),
        creator: creator.to_owned(),
        moderation_state: uploaded.moderation_state,
        uploaded: humantime::format_rfc3339_seconds(SystemTime::now()).to_string(),
    })
}

/// Reads the file again, checks that it did not change since the scan and
/// sends it.
fn start_upload(
    client: &OpenCloud,
    config: &Config,
    source: &Source,
) -> anyhow::Result<StartedUpload> {
    let bytes =
        fs::read(&source.path).with_context(|| format!("Cannot read {}", source.path.display()))?;
    if blake3::hash(&bytes).to_hex().as_str() != source.hash {
        bail!(
            "{} changed while syncing; run `rojo assets sync` again",
            source.rel
        );
    }
    let stem = source
        .rel
        .rsplit_once('.')
        .map_or(source.rel.as_str(), |(stem, _)| stem);
    let display_name: String = format!("{}{}", config.name_prefix, stem.replace('/', "."))
        .chars()
        .take(MAX_DISPLAY_NAME_CHARS)
        .collect();
    let description = config
        .description
        .clone()
        .unwrap_or_else(|| format!("Uploaded by rojo assets sync from {}", source.rel));
    let description: String = description.chars().take(MAX_DESCRIPTION_CHARS).collect();
    // The name only labels the upload, so characters that cannot go in a
    // multipart header are replaced instead of failing the upload.
    let file_name: String = source
        .rel
        .rsplit('/')
        .next()
        .unwrap_or(&source.rel)
        .chars()
        .map(|c| {
            if c == '"' || c == '\\' || c.is_control() {
                '_'
            } else {
                c
            }
        })
        .collect();

    client
        .start_asset_upload(
            source.kind.asset_type(),
            &display_name,
            &description,
            config.creator,
            &file_name,
            source.content_type,
            &bytes,
        )
        .map_err(|error| {
            // Without an operation there is nothing to resume.
            let hint = if error.may_have_applied() {
                " Roblox may still have created the asset; check the creator's assets before \
                 running sync again, since a rerun uploads the file again."
            } else {
                ""
            };
            anyhow::anyhow!("Could not upload {}: {error}.{hint}", source.rel)
        })
}

