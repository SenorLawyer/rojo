    /// A fake Open Cloud Assets API. Each upload gets the next id from 1001
    /// and finishes at once, unless `defer` is set: then the upload returns
    /// an unfinished operation that a later poll finishes, and polls are
    /// refused with 403 while `refuse_polls` is set. A file containing
    /// `REJECTME` or `REVIEWME` is rejected or left under review, and the
    /// upload numbered `fail_at` returns 400.
    struct FakeCloud {
        base: String,
        uploads: Arc<Mutex<Vec<String>>>,
        /// Every request line, such as `GET /assets/v1/operations/op1`.
        requests: Arc<Mutex<Vec<String>>>,
        defer: Arc<AtomicBool>,
        refuse_polls: Arc<AtomicBool>,
        /// Polls report the operation as finished and failed.
        fail_polls: Arc<AtomicBool>,
    }

    impl FakeCloud {
        fn start(fail_at: Option<usize>) -> FakeCloud {
            let listener = TcpListener::bind("127.0.0.1:0").unwrap();
            let base = format!("http://{}", listener.local_addr().unwrap());
            let uploads = Arc::new(Mutex::new(Vec::new()));
            let requests = Arc::new(Mutex::new(Vec::new()));
            let defer = Arc::new(AtomicBool::new(false));
            let refuse_polls = Arc::new(AtomicBool::new(false));
            let fail_polls = Arc::new(AtomicBool::new(false));
            let failing = Arc::clone(&fail_polls);
            let log = Arc::clone(&uploads);
            let request_log = Arc::clone(&requests);
            let deferring = Arc::clone(&defer);
            let refusing = Arc::clone(&refuse_polls);
            std::thread::spawn(move || {
                for stream in listener.incoming() {
                    let mut stream = stream.unwrap();
                    stream
                        .set_read_timeout(Some(Duration::from_secs(5)))
                        .unwrap();
                    let (head, body) = read_request(&mut stream);
                    let request_line = head.lines().next().unwrap_or("");
                    let request_line = request_line
                        .rsplit_once(' ')
                        .map_or(request_line, |(line, _)| line)
                        .to_owned();
                    request_log.lock().unwrap().push(request_line.clone());
                    if let Some(number) = request_line.strip_prefix("GET /assets/v1/operations/op")
                    {
                        let (status, reply) = if failing.load(Ordering::SeqCst) {
                            (
                                "200 OK",
                                format!(
                                    r#"{{"path":"operations/op{number}","done":true,"error":{{"code":"INVALID_ARGUMENT","message":"bad file"}}}}"#
                                ),
                            )
                        } else if refusing.load(Ordering::SeqCst) {
                            (
                                "403 Forbidden",
                                r#"{"message":"missing scope asset:read"}"#.to_owned(),
                            )
                        } else {
                            let number: u64 = number.parse().unwrap();
                            (
                                "200 OK",
                                format!(
                                    r#"{{"path":"operations/op{number}","done":true,"response":{{"assetId":"{}","moderationResult":{{"moderationState":"Approved"}}}}}}"#,
                                    1000 + number
                                ),
                            )
                        };
                        write!(
                            stream,
                            "HTTP/1.1 {status}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{reply}",
                            reply.len()
                        )
                        .unwrap();
                        continue;
                    }
                    assert!(
                        head.starts_with("POST /assets/v1/assets "),
                        "unexpected request {head}"
                    );
                    let body_text = String::from_utf8_lossy(&body).into_owned();
                    let display_name = body_text
                        .split("\"displayName\":\"")
                        .nth(1)
                        .and_then(|rest| rest.split('"').next())
                        .unwrap_or("")
                        .to_owned();
                    let asset_type = body_text
                        .split("\"assetType\":\"")
                        .nth(1)
                        .and_then(|rest| rest.split('"').next())
                        .unwrap_or("")
                        .to_owned();
                    let number = {
                        let mut log = log.lock().unwrap();
                        log.push(display_name);
                        log.len()
                    };
                    let (status, reply) = if Some(number) == fail_at {
                        ("400 Bad Request", r#"{"message":"bad file"}"#.to_owned())
                    } else if deferring.load(Ordering::SeqCst) {
                        (
                            "200 OK",
                            format!(r#"{{"path":"operations/op{number}","done":false}}"#),
                        )
                    } else {
                        let state = if body_text.contains("REJECTME") {
                            "Rejected"
                        } else if body_text.contains("REVIEWME") {
                            "Reviewing"
                        } else {
                            "Approved"
                        };
                        (
                            "200 OK",
                            format!(
                                r#"{{"path":"operations/op{number}","done":true,"response":{{"assetId":"{}","assetType":"{asset_type}","moderationResult":{{"moderationState":"{state}"}}}}}}"#,
                                1000 + number
                            ),
                        )
                    };
                    write!(
                        stream,
                        "HTTP/1.1 {status}\r\nContent-Type: application/json\r\nContent-Length: {}\r\nConnection: close\r\n\r\n{reply}",
                        reply.len()
                    )
                    .unwrap();
                }
            });
            FakeCloud {
                base,
                uploads,
                requests,
                defer,
                refuse_polls,
                fail_polls,
            }
        }

        fn client(&self) -> anyhow::Result<OpenCloud> {
            Ok(OpenCloud::with_base_url("fixture-key", &self.base)?.with_fast_timing())
        }

        fn uploads(&self) -> Vec<String> {
            self.uploads.lock().unwrap().clone()
        }

        fn requests(&self) -> Vec<String> {
            self.requests.lock().unwrap().clone()
        }
    }

    fn read_request(stream: &mut std::net::TcpStream) -> (String, Vec<u8>) {
        let mut data = Vec::new();
        let mut chunk = [0; 4096];
        let head_end = loop {
            let n = stream.read(&mut chunk).unwrap();
            assert!(n > 0, "client closed the connection early");
            data.extend_from_slice(&chunk[..n]);
            if let Some(i) = data.windows(4).position(|w| w == b"\r\n\r\n") {
                break i + 4;
            }
        };
        let head = String::from_utf8_lossy(&data[..head_end]).into_owned();
        let length: usize = head
            .lines()
            .find_map(|line| {
                let (name, value) = line.split_once(':')?;
                name.eq_ignore_ascii_case("content-length")
                    .then(|| value.trim().parse().unwrap())
            })
            .unwrap_or(0);
        while data.len() < head_end + length {
            let n = stream.read(&mut chunk).unwrap();
            assert!(n > 0, "client closed the connection early");
            data.extend_from_slice(&chunk[..n]);
        }
        (head, data[head_end..head_end + length].to_vec())
    }

    /// A PNG header with the given size, followed by `tag` so that files
    /// differ. Only the header is checked before uploading.
    fn png(width: u32, height: u32, tag: &str) -> Vec<u8> {
        let mut bytes = b"\x89PNG\r\n\x1a\n\0\0\0\x0dIHDR".to_vec();
        bytes.extend_from_slice(&width.to_be_bytes());
        bytes.extend_from_slice(&height.to_be_bytes());
        bytes.extend_from_slice(&[8, 6, 0, 0, 0, 0, 0, 0, 0]);
        bytes.extend_from_slice(tag.as_bytes());
        bytes
    }

