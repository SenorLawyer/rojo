    fn read_request(stream: &mut std::net::TcpStream) -> (String, Vec<u8>) {
        let mut data = Vec::new();
        let mut chunk = [0; 4096];
        let head_end = loop {
            let n = stream.read(&mut chunk).unwrap();
            assert!(n > 0, "client closed the connection early");
            data.extend_from_slice(&chunk[..n]);
            if let Some(i) = data.windows(4).position(|w| w == b"\r\n\r\n") {
                break i + 4;
            }
        };
        let head = String::from_utf8_lossy(&data[..head_end]).into_owned();
        let length: usize = head
            .lines()
            .find_map(|line| {
                let (name, value) = line.split_once(':')?;
                name.eq_ignore_ascii_case("content-length")
                    .then(|| value.trim().parse().unwrap())
            })
            .unwrap_or(0);
        while data.len() < head_end + length {
            let n = stream.read(&mut chunk).unwrap();
            assert!(n > 0, "client closed the connection early");
            data.extend_from_slice(&chunk[..n]);
        }
        (head, data[head_end..head_end + length].to_vec())
    }

    /// A PNG header with the given size, followed by `tag` so that files
    /// differ. Only the header is checked before uploading.
    fn png(width: u32, height: u32, tag: &str) -> Vec<u8> {
        let mut bytes = b"\x89PNG\r\n\x1a\n\0\0\0\x0dIHDR".to_vec();
        bytes.extend_from_slice(&width.to_be_bytes());
        bytes.extend_from_slice(&height.to_be_bytes());
        bytes.extend_from_slice(&[8, 6, 0, 0, 0, 0, 0, 0, 0]);
        bytes.extend_from_slice(tag.as_bytes());
        bytes
    }

