        // A pending upload of contents that no file has any more is dropped.
        let fixture = Fixture::new();
        fixture.write("C.png", &png(8, 8, "c"));
        let cloud = FakeCloud::start(None);
        cloud.defer.store(true, Ordering::SeqCst);
