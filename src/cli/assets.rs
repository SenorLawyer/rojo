    #[test]
    fn image_sizes_are_read_from_headers() {
        assert_eq!(image_size("png", &png(16, 9, "")), Some((16, 9)));
        let mut bmp = b"BM".to_vec();
        bmp.resize(26, 0);
        bmp[18..22].copy_from_slice(&20i32.to_le_bytes());
        bmp[22..26].copy_from_slice(&(-30i32).to_le_bytes());
        assert_eq!(image_size("bmp", &bmp), Some((20, 30)));
        let mut tga = vec![0; 18];
        tga[12..14].copy_from_slice(&64u16.to_le_bytes());
        tga[14..16].copy_from_slice(&32u16.to_le_bytes());
        assert_eq!(image_size("tga", &tga), Some((64, 32)));
        // SOI, an APP0 segment, then SOF0 with height 0x0102 and width 0x0304.
        let jpeg = b"\xFF\xD8\xFF\xE0\x00\x04ab\xFF\xC0\x00\x11\x08\x01\x02\x03\x04\x03";
        assert_eq!(image_size("jpg", jpeg), Some((0x0304, 0x0102)));
        assert_eq!(image_size("jpg", b"\xFF\xD8\xFF\xD9"), None);
    }

