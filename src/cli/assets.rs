//! `rojo assets`: uploads the images, audio and models in a folder through
//! Open Cloud and writes a Luau module of their ids.
//!
//! # Design
//!
//! - The settings live in their own `assets.toml` rather than in a project
//!   file: project files describe an instance tree that `rojo build` and
//!   `rojo serve` read without network access or credentials, while asset
//!   uploads are a separate step that a team runs on purpose.
//! - Upload state lives in a lockfile next to the config (`assets.toml` uses
//!   `assets.lock.json`), meant to be committed so that everyone shares one
//!   set of asset ids. Each entry keys a file's path relative to the source
//!   folder to the BLAKE3 hash of its contents and the id it was uploaded as.
//!   A file is only uploaded when no entry with the same hash, asset type and
//!   creator exists, so renaming, moving or copying a file reuses its id.
//! - Files that disappear are dropped from the lockfile and the module but
//!   never deleted on Roblox: the Assets API cannot delete assets, and older
//!   places may still use them.
//! - Every file is read, hashed and checked against Open Cloud's limits
//!   before anything is uploaded, so a bad file fails the run without leaving
//!   half of a batch uploaded. Reruns read every file again; BLAKE3 hashes
//!   hundreds of megabytes per second, so this stays fast without caching
//!   modification times.
//! - The lockfile is written atomically (temporary file and rename) after
//!   every successful upload, so a later run does not upload a file whose
//!   upload finished. Once Roblox has accepted an upload and returned its
//!   operation, the operation is recorded under `pending` before polling
//!   starts; if polling then fails or times out, the next run polls that
//!   operation instead of sending the file again. Only an upload interrupted
//!   between sending the file and recording the operation can be repeated,
//!   and its error says so. The module is only written once every upload
//!   succeeded.
//! - A run that has nothing to upload never reads the API key, so it works
//!   on machines and CI jobs without one.
//! - Ids are never reused across creators, so changing the creator (such as
//!   moving a game to a group) uploads everything again. Each old id is
//!   recorded under `replaced` with its new id, since the path-keyed entries
//!   are overwritten, and `remap` uses those records to rewrite old ids in
//!   the project's text files. Only creator changes are recorded: a changed
//!   file for the same creator is a different asset, and code using its old
//!   id may mean the old contents.

