return function()
	local formatValue = require(script.Parent.formatValue)

	it("shows position, orientation and units in a CFrame patch", function()
		expect(formatValue(CFrame.new(1, 2, 3))).to.equal("(1, 2, 3), (0 deg, 0 deg, 0 deg)")
	end)
	it("preserves sub-millistud differences", function()
		expect(formatValue(Vector3.new(0, 0, 0)) == formatValue(Vector3.new(0, 0.0001, 0))).to.equal(false)
	end)
	it("shows float32 components without double-precision noise", function()
		expect(formatValue(Vector3.new(0, 0.0001, 0.1))).to.equal("(0, 0.0001, 0.1)")
		expect(formatValue(Vector2.new(0.3, -12.5))).to.equal("(0.3, -12.5)")
		expect(formatValue(UDim2.new(0.1, 5, 0.25, -3))).to.equal("{0.1, 5}, {0.25, -3}")
		expect(formatValue(NumberRange.new(0.1, 0.7))).to.equal("[0.1, 0.7]")
	end)
	it("keeps the smallest float32 step visible", function()
		local one = Vector3.new(1, 0, 0)
		local nextAfterOne = Vector3.new(1 + 2 ^ -23, 0, 0)
		expect(formatValue(one) == formatValue(nextAfterOne)).to.equal(false)
	end)
	it("writes large whole components without an exponent", function()
		expect(formatValue(Vector3.new(123456789, 0, 0))).to.equal("(123456792, 0, 0)")
	end)
end
